"""
=============================================================================
[decorators.py] 데이터 흐름, 함수 순서도 및 쉬운 업무 해설
=============================================================================

1. 데이터가 들어오고 나갈 때의 함수 순서도:
   사용자가 명령어를 실행함 (예: add, list 등)
       │
       ▼ [1단계] handle_cli_errors 래퍼(wrapper)가 함수를 감싸고 실행을 지켜봄
       │
       ▼ [2단계] 원본 함수 실행 시도 (try)
       │         가계부 화면이나 계산기 코드가 정상적으로 돌아감
       │
       ├── [문제없이 성공한 경우]
       │   └── 결과를 손님 모니터에 그대로 보여주고 마무리!
       │
       └── [도중에 실수가 터진 경우!] (예: 잘못된 날짜, 없는 카테고리 등)
           │
           ▼ [3단계] except 절이 터진 폭탄(에러)을 허공에서 낚아챔
           │         무시무시한 빨간 영어 에러 글자(Traceback)가 화면에 도배되는 것을 차단!
           │
           ▼ [4단계] 콘솔 출력
           │         [오류 원인] 잘못된 날짜 형식입니다.
           │         [해결 힌트] YYYY-MM-DD 형식으로 다시 적어주세요.
           │
           ▼ [5단계] sys.exit(1) 호출
                     프로그램이 조용하고 안전하게 문을 닫고 종료함

2. 이 파일의 진짜 업무 (전문용어 0% 쉬운 설명):
   [1차 설명: 코드가 실제로 하는 일]
   - 프로그램이 실행되다가 중간에 에러가 발생했을 때, 프로그램이 튕기면서 무서운 영어 코드가 
     화면에 쏟아지지 않도록 막아주고, 사람이 읽기 쉬운 친절한 한국어 힌트를 보여준 뒤 안전하게 끝마칩니다.

   [2차 업무/비유 설명: 실제 실생활 업무 관점]
   - 서커스 공연장 바닥에 깔아둔 [푹신한 안전 그물망]이자 [친절한 안내원]입니다.
   - 곡예사가 줄을 타다가 발을 헛디뎠을 때, 그물망이 없으면 바닥에 부딪혀 피를 흘리며 관객들이 공포에 질립니다.
   - 바닥에 에어백 그물망을 깔아두면 다치지 않고 안전하게 튕겨 올라옵니다.
   - 그리고 안내원이 마이크로 "관객 여러분, 손잡이가 미끄러워 공연이 잠시 멈췄습니다. 잠시 후 다시 시작해 주세요!" 하고 
     정중하게 안내 방송을 한 뒤 조용히 무대 커튼을 내리는 업무를 전담합니다.
=============================================================================
"""

# [1차 설명]: 함수를 감싸는 포장지(데코레이터)를 만들 때 원래 함수의 이름표가 지워지지 않게 돕는 도구입니다.
# [2차 업무 설명]: 안내원 옷을 입혀도 "이 사람의 원래 직책은 누구인가"를 명찰에 그대로 보존해 주는 일입니다.
import functools
# [1차 설명]: 운영체제 환경변수를 확인하기 위한 도구입니다.
# [2차 업무 설명]: 개발자 전용 디버그 스위치가 켜져 있는지 확인하는 일입니다.
import os
# [1차 설명]: 에러 전용 콘솔 창에 글을 쓰고 프로그램을 안전하게 끝마치기 위해 가져옵니다.
# [2차 업무 설명]: 빨간색 경고 안내 방송을 내보내고, 안전하게 매장 셔터를 내리는 일입니다.
import sys
# [1차 설명]: 작업에 걸린 시간을 초 단위로 정밀하게 재기 위해 가져옵니다.
# [2차 업무 설명]: 스톱워치를 들고 "이 손님 주문 처리하는 데 몇 초 걸렸나" 재보는 일입니다.
import time
# [1차 설명]: 어떤 형태의 함수든 유연하게 받아들이기 위해 타입 도구를 가져옵니다.
# [2차 업무 설명]: 어떤 직원이 오든 상관없이 다 입을 수 있는 프리사이즈 경호원 조끼를 준비하는 일입니다.
from typing import Any, Callable, TypeVar

# [1차 설명]: 임의의 함수 형태를 나타내는 제네릭 타입 상자입니다.
# [2차 업무 설명]: 어떤 함수든 쏙 들어올 수 있는 빈 상자입니다.
F = TypeVar("F", bound=Callable[..., Any])


# [1차 설명]: 모든 콘솔 명령어의 에러를 가로채서 친절히 안내해 주는 데코레이터 함수입니다.
# [2차 업무 설명]: 명령어 실행 시 바닥에 푹신하게 깔아두는 [안전 에어백 매트리스]입니다.
# 마이: 여기서 func은 cli에서 @handle_cli_errors 밑에 있던 함수란 의미
# 마이: F = TypeVar("F", bound=Callable[..., Any])는 F라는 타입 변수를 정의하는 것으로, Callable[..., Any]는 임의의 인자와 반환값을 가지는 함수를 나타냅니다. 
# 즉, F는 어떤 형태의 함수든 될 수 있는 제네릭 타입입니다. 그러니까 함수를 넣어 일부 수정등이 된 함수가 나오는 구조라는 거임.
def handle_cli_errors(func: F) -> F:
    # [1차 설명]: 원래 함수의 이름과 설명을 래퍼 함수에 그대로 붙여둡니다.
    # [2차 업무 설명]: 경호원 조끼 겉면에 원래 담당 직원의 이름표를 그대로 달아주는 일입니다.
    # 마이: functools: 함수(데코레이터/고차함수) 관련 유틸을 모아놓은 표준 모듈.
    @functools.wraps(func)
    # [1차 설명]: 원래 함수 대신 실제로 바깥에서 실행되며 에러를 감시하는 래퍼 함수입니다.
    # [2차 업무 설명]: 손님의 주문 과정을 옆에서 지켜보며 사고가 나지 않나 지키는 경호원입니다.
    # 마이: *args는 리스트형자료, **kwargs는 딕셔너리형 자료. 즉, 원래 함수가 어떤 인자를 받든 그대로 받아서 func에 전달하는 구조.
    # 마이: 애니를 ㄹ쓴건 어떤 형태의 자료형도 받아서 어떤 형태의 자료로 내보내라는 오더인셈 
    def wrapper(*args: Any, **kwargs: Any) -> Any:
        # [1차 설명]: 에러가 날 가능성이 있는 원래 함수를 일단 실행해 봅니다.
        # [2차 업무 설명]: 손님의 요청대로 가계부 작업을 일단 순조롭게 진행해 봅니다.
        try:
            # 마이: 여기서 실행 시키고 실행에 성공하면 그 값을 그대로 내보내고 안되면 익셉트로 넘어가는 구조
            return func(*args, **kwargs)

        # [1차 설명]: 잘못된 날짜나 음수 금액 같은 값 오류(ValueError)를 잡습니다.
        # [2차 업무 설명]: 손님이 날짜에 오타를 냈거나 마이너스 돈을 적어서 퇴짜 맞았을 때 경호원이 달려와 친절히 안내합니다.
        except ValueError as ve:
            # [1차 설명]: 오류 원인을 표준 에러 콘솔(stderr)로 빨간색 느낌으로 출력합니다.
            # [2차 업무 설명]: 손님이 무엇을 잘못 적었는지 ve에 담긴 구체적인 이유를 화면에 보여줍니다.
            print(f"\n[오류 원인] 잘못된 값 또는 형식이 전달되었습니다: {ve}", file=sys.stderr)
            # [1차 설명]: 해결 힌트를 친절하게 안내합니다.
            # [2차 업무 설명]: "날짜는 YYYY-MM-DD, 금액은 양수로 쓰세요" 하고 손님이 바로 고칠 수 있는 처방전을 줍니다.
            print("[해결 힌트] 날짜(YYYY-MM-DD), 양수 금액, 허용된 카테고리인지 다시 확인하세요.", file=sys.stderr)
            # [1차 설명]: 비정상 종료 코드 1로 프로그램을 안전하게 종료합니다.
            # [2차 업무 설명]: sys.exit(1)은 에러가 났음을 컴퓨터에 알리며 매장 문을 안전하게 닫는 일입니다.
            sys.exit(1)

        # [1차 설명]: 필수 데이터 항목이 빠졌을 때 터지는 KeyError를 잡습니다.
        # [2차 업무 설명]: 서류에 필수 항목이 쏙 빠져있을 때 친절히 알려주고 셔터를 내립니다.
        except KeyError as ke:
            # [1차 설명]: 누락된 항목이 무엇인지 에러 콘솔에 출력합니다.
            # [2차 업무 설명]: 빠뜨린 필수 단어(ke)가 무엇인지 손님에게 콕 짚어 알려줍니다.
            print(f"\n[오류 원인] 필수 데이터 항목이 누락되었습니다: {ke}", file=sys.stderr)
            # [1차 설명]: 입력 데이터 형식 확인 힌트를 안내합니다.
            # [2차 업무 설명]: 빠진 칸이 없는지 서류를 다시 확인하라고 안내합니다.
            print("[해결 힌트] 입력 데이터의 형식과 필수 필드 존재 여부를 확인하세요.", file=sys.stderr)
            # [1차 설명]: 프로그램 문을 닫고 종료합니다.
            # [2차 업무 설명]: 잘못된 데이터로 계속 진행하지 않도록 종료합니다.
            sys.exit(1)

        # [1차 설명]: 장부 파일이나 폴더를 찾을 수 없을 때 터지는 FileNotFoundError를 잡습니다.
        # [2차 업무 설명]: 장부 파일이 어디론가 사라졌을 때 길을 잃지 않도록 경로를 확인하라고 안내합니다.
        except FileNotFoundError as fe:
            # [1차 설명]: 찾지 못한 파일 경로를 출력합니다.
            # [2차 업무 설명]: fe.filename에 담긴 사라진 장부 파일 이름을 보여줍니다.
            print(f"\n[오류 원인] 요청한 파일 또는 경로를 찾을 수 없습니다: {fe.filename}", file=sys.stderr)
            # [1차 설명]: 폴더 경로 확인 힌트를 안내합니다.
            # [2차 업무 설명]: --data-dir 저장 폴더 이름에 오타가 없는지 확인하라고 팁을 줍니다.
            print("[해결 힌트] 파일 경로가 올바른지, --data-dir 옵션 값에 오타가 없는지 확인하세요.", file=sys.stderr)
            # [1차 설명]: 안전하게 종료합니다.
            sys.exit(1)

        # [1차 설명]: 파일 읽기/쓰기 권한이 없을 때 터지는 PermissionError를 잡습니다.
        # [2차 업무 설명]: 컴퓨터 보안 때문에 파일에 글씨를 쓸 수 없을 때 권한을 확인하라고 안내합니다.
        except PermissionError as pe:
            # [1차 설명]: 권한이 없는 파일 이름을 출력합니다.
            # [2차 업무 설명]: 컴퓨터가 접근을 거부한 파일 이름을 알려줍니다.
            print(f"\n[오류 원인] 파일에 접근할 수 있는 시스템 권한이 없습니다: {pe.filename}", file=sys.stderr)
            # [1차 설명]: 파일 쓰기 권한 점검 힌트를 안내합니다.
            # [2차 업무 설명]: 관리자 권한이나 파일 잠금을 확인하라고 팁을 줍니다.
            print("[해결 힌트] 대상 디렉터리나 파일의 읽기/쓰기 권한을 확인하세요.", file=sys.stderr)
            # [1차 설명]: 안전하게 프로그램을 종료합니다.
            sys.exit(1)

        # [1차 설명]: 사용자가 Ctrl+C를 눌러서 강제로 취소했을 때를 잡습니다.
        # [2차 업무 설명]: 손님이 작업 도중에 "아, 취소할게요!" 하고 나갔을 때 놀라지 않고 안전하게 보내드립니다.
        except KeyboardInterrupt:
            # [1차 설명]: 사용자에 의한 취소 메시지를 출력합니다.
            # [2차 업무 설명]: 빨간 에러 폭탄 대신 "작업이 취소되었습니다"라고 부드럽게 안내합니다.
            print("\n\n[작업 취소] 사용자에 의해 작업이 취소되었습니다.", file=sys.stderr)
            # [1차 설명]: 종료 안내 힌트를 출력합니다.
            # [2차 업무 설명]: 필요할 때 언제든 다시 명령을 쳐달라고 안내합니다.
            print("[해결 힌트] 안전하게 종료되었습니다. 필요할 때 다시 명령을 실행하세요.", file=sys.stderr)
            # [1차 설명]: 종료 코드를 남기고 마칩니다.
            sys.exit(1)

        # [1차 설명]: 위에서 미처 생각하지 못한 세상의 그 어떤 에러가 터져도 여기서 다 잡아냅니다.
        # [2차 업무 설명]: 예상치 못한 돌발 사고가 나도 무서운 화면이 안 뜨게 막아주는 최종 그물망입니다.
        except Exception as e:
            # [1차 설명]: 발생한 예외 내용을 출력합니다.
            # [2차 업무 설명]: e에 담긴 예상치 못한 돌발 상황 원인을 화면에 찍어줍니다.
            print(f"\n[시스템 오류] 예기치 않은 오류가 발생했습니다: {e}", file=sys.stderr)
            # [1차 설명]: 명령어 형식 점검 힌트를 출력합니다.
            # [2차 업무 설명]: 명령어 단어나 옵션 표기가 올바른지 점검하라고 안내합니다.
            print("[해결 힌트] 인자 표기(--) 및 명령어 형식이 명세와 일치하는지 점검하세요.", file=sys.stderr)
            # [1차 설명]: 프로그램을 안전하게 마칩니다.
            sys.exit(1)

    # [1차 설명]: 에어백 옷이 입혀진 함수를 반환합니다.
    # [2차 업무 설명]: 안전장치가 완료된 카운터 안내원을 현장으로 내보내는 일입니다.
    return wrapper  # type: ignore[return-value]


# [1차 설명]: 함수가 실행되는 데 걸린 시간을 재주는 데코레이터입니다.
# [2차 업무 설명]: 스톱워치로 직원의 업무 처리 속도를 재보는 [속도 측정기]입니다.
def measure_time(func: F) -> F:
    # [1차 설명]: 원래 함수의 이름표를 보존합니다.
    # [2차 업무 설명]: 스톱워치 측정 옷을 입혀도 원래 직원의 명찰을 유지시킵니다.
    @functools.wraps(func)
    # [1차 설명]: 실행 시간을 측정하며 함수를 감싸는 래퍼입니다.
    # [2차 업무 설명]: 스톱워치를 들고 시간을 재어주는 보조 직원입니다.
    def wrapper(*args: Any, **kwargs: Any) -> Any:
        # [1차 설명]: 시작 시점의 고정밀 시계 시간을 잽니다.
        # [2차 업무 설명]: 손님 주문이 들어오자마자 스톱워치 버튼을 찰칵 누르는 일입니다.
        start_time = time.perf_counter()
        # [1차 설명]: 함수 실행을 시도합니다.
        # [2차 업무 설명]: 원래 작업을 수행합니다.
        try:
            # [1차 설명]: 원래 함수를 실행하고 그 결과물을 받아서 돌려줍니다.
            # [2차 업무 설명]: 주문받은 음식을 손님에게 건네주는 일입니다.
            return func(*args, **kwargs)
        # [1차 설명]: 작업이 성공하든 에러가 나든 무조건 마지막에 실행됩니다.
        # [2차 업무 설명]: 일이 어떻게 끝났든 상관없이 반드시 스톱워치를 멈추는 일입니다.
        finally:
            # [1차 설명]: 현재 시간에서 시작 시간을 빼서 걸린 시간을 계산합니다.
            # [2차 업무 설명]: (끝난 시간 - 시작 시간) 연산으로 총 몇 초가 걸렸는지 계산합니다.
            elapsed_time = time.perf_counter() - start_time
            # [1차 설명]: 디버그 모드가 켜져 있는지 확인합니다.
            # [2차 업무 설명]: 개발자 전용 스위치(BUDGET_DEBUG=1)가 켜져 있을 때만 콘솔에 시간을 출력합니다.
            if os.getenv("BUDGET_DEBUG") == "1":
                # [1차 설명]: 걸린 시간을 소수점 6자리 초 단위로 출력합니다.
                # [2차 업무 설명]: "이 함수 처리하는 데 0.001234초 걸렸습니다" 하고 개발자에게 보고합니다.
                print(f"[DEBUG LOG] {func.__name__} 실행 소요 시간: {elapsed_time:.6f}초", file=sys.stderr)
    # [1차 설명]: 시간 측정 기능이 장착된 래퍼를 반환합니다.
    # [2차 업무 설명]: 스톱워치를 든 직원을 배치합니다.
    return wrapper  # type: ignore[return-value]


# [1차 설명]: 어떤 작업이 시작되고 끝났는지 기록해 주는 데코레이터입니다.
# [2차 업무 설명]: 직원이 업무를 시작하고 마칠 때마다 출석부에 도장을 쾅쾅 찍어주는 [작업 기록기]입니다.
def log_operation(action_name: str) -> Callable[[F], F]:
    # [1차 설명]: 실제 함수를 전달받는 내부 장식자 함수입니다.
    # [2차 업무 설명]: 어떤 업무를 기록할지 작업 이름을 받아 준비하는 틀입니다.
    def decorator(func: F) -> F:
        # [1차 설명]: 원래 함수의 명찰을 보존합니다.
        # [2차 업무 설명]: 원래 직원의 이름을 잃어버리지 않게 래퍼에 달아줍니다.
        @functools.wraps(func)
        # [1차 설명]: 작업 전후로 로그를 찍는 래퍼 함수입니다.
        # [2차 업무 설명]: 작업 시작과 끝을 기록부에 적어주는 기록원입니다.
        def wrapper(*args: Any, **kwargs: Any) -> Any:
            # [1차 설명]: 디버그 스위치가 켜져 있는지 확인합니다.
            # [2차 업무 설명]: 개발자 로그 모드가 켜져 있을 때만 기록을 남깁니다.
            if os.getenv("BUDGET_DEBUG") == "1":
                # [1차 설명]: 작업 시작 안내 메시지를 출력합니다.
                # [2차 업무 설명]: "지금부터 '거래 추가' 작업을 시작합니다!" 하고 기록을 남깁니다.
                print(f"[DEBUG LOG] 작업 시작: '{action_name}' (함수: {func.__name__})", file=sys.stderr)
            # [1차 설명]: 원래 함수를 실행하여 결과물을 받습니다.
            # [2차 업무 설명]: 실제 회계 작업을 수행하고 영수증이나 결산 결과를 result에 받습니다.
            result = func(*args, **kwargs)
            # [1차 설명]: 디버그 스위치가 켜져 있는지 확인합니다.
            # [2차 업무 설명]: 로그 모드가 켜져 있는지 다시 확인합니다.
            if os.getenv("BUDGET_DEBUG") == "1":
                # [1차 설명]: 작업 완료 메시지를 출력합니다.
                # [2차 업무 설명]: "'거래 추가' 작업을 무사히 끝마쳤습니다!" 하고 기록을 남깁니다.
                print(f"[DEBUG LOG] 작업 완료: '{action_name}'", file=sys.stderr)
            # [1차 설명]: 원래 함수의 실행 결과를 호출자에게 그대로 넘겨줍니다.
            # [2차 업무 설명]: 완성된 결과물을 손님에게 전달합니다.
            return result
        # [1차 설명]: 완성된 래퍼 함수를 돌려줍니다.
        # [2차 업무 설명]: 기록원 기능이 탑재된 직원을 반환합니다.
        return wrapper  # type: ignore[return-value]
    # [1차 설명]: 데코레이터 함수를 돌려줍니다.
    # [2차 업무 설명]: 장식 도구를 완성하여 내보냅니다.
    return decorator