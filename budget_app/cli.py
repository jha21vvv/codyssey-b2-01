# [1차 설명]: 올바른 날짜를 입력받을 때까지 계속 질문하는 함수입니다.
# [2차 설명]: prompt는 '질문을 던져 입력을 유도하다'라는 뜻으로, 손님에게 날짜를 묻고 오타가 나면 다시 묻는 창구입니다.
def prompt_date() -> str:
    # [1차 설명]: 올바른 날짜가 입력되어 return을 만날 때까지 영원히 반복합니다.
    # [2차 설명]: while True는 '조건이 참인 한 무한히 반복하라'는 뜻으로, 손님이 똑바로 적을 때까지 질문을 반복하는 루프입니다.
    while True:
        # [1차 설명]: 키보드로 날짜 글자를 입력받고 양쪽의 불필요한 공백을 잘라냅니다.
        # [2차 설명]: input()은 화면에 질문을 띄우고 손님이 엔터 칠 때까지 기다리는 함수이며, .strip()은 실수로 누른 스페이스바 빈칸을 지워주는 함수입니다.
        val = input("1. 날짜 (YYYY-MM-DD): ").strip()
        # [1차 설명]: 입력한 날짜가 진짜 달력에 존재하는지 검사를 시도합니다.
        # [2차 설명]: try는 '일단 시험 삼아 아래 코드를 실행해 봐라'라는 뜻의 감시 구문입니다.
        try:
            # [1차 설명]: 문자열을 "년-월-일" 달력 날짜 형식으로 변환해 봅니다.
            # [2차 설명]: strptime은 'String Parse Time'의 줄임말로, 글자(String)를 쪼개서 진짜 달력 날짜로 맞추어보는 함수입니다.
            datetime.strptime(val, "%Y-%m-%d")
            # [1차 설명]: 올바른 날짜이면 입력받은 글자를 호출자에게 돌려주고 루프를 끝냅니다.
            # [2차 설명]: return val은 '합격했으니 입력받은 날짜 값을 가지고 이 함수를 탈출하라'는 뜻입니다.
            return val
        # [1차 설명]: 달력에 없는 엉터리 날짜이거나 글자 모양이 틀렸을 때 발생하는 에러를 잡습니다.
        # [2차 설명]: except ValueError는 '값에 문제가 있어서 에러가 터졌다면 프로그램을 죽이지 말고 아래 안내를 실행하라'는 뜻입니다.
        except ValueError:
            # [1차 설명]: 형식 안내 오류 메시지를 콘솔 화면에 보여줍니다.
            # [2차 설명]: print()는 모니터 화면에 글자를 찍어주는 가장 기본적인 출력 함수입니다.
            print("   [입력 오류] 'YYYY-MM-DD' 형식(예: 2026-05-15)으로 정확히 입력하세요.")


# [1차 설명]: 수입(income) 또는 지출(expense) 단어를 입력받는 함수입니다.
# [2차 설명]: prompt_type은 오늘 거래가 내 지갑으로 들어온 돈인지 나간 돈인지 손님에게 물어보는 질문 창구입니다.
def prompt_type() -> str:
    # [1차 설명]: 올바른 단어를 적을 때까지 계속 반복합니다.
    # [2차 설명]: while True로 무한 루프를 돌아 잘못 적었을 때 다시 입력을 받습니다.
    while True:
        # [1차 설명]: 키보드로 입력을 받아 공백을 지우고 모두 영어 소문자로 바꿉니다.
        # [2차 설명]: .lower()는 대문자 'INCOME'을 소문자 'income'으로 바꿔주어, 대소문자 상관없이 편하게 입력하게 해주는 함수입니다.
        val = input("2. 타입 (income/expense): ").strip().lower()
        # [1차 설명]: 입력한 단어가 "income"이나 "expense" 둘 중 하나에 포함되는지 확인합니다.
        # [2차 설명]: in ("income", "expense")는 튜플 안의 두 단어 목록 중에 손님이 쓴 단어가 들어있는지 확인하는 문법입니다.
        if val in ("income", "expense"):
            # [1차 설명]: 올바른 단어이면 그 단어를 반환하고 종료합니다.
            # [2차 설명]: 합격한 타입 문자열을 가지고 함수를 빠져나갑니다.
            return val
        # [1차 설명]: 다른 이상한 외계어를 적었을 때 경고 메시지를 출력합니다.
        # [2차 설명]: 손님에게 수입은 income, 지출은 expense로만 적으라고 친절히 안내합니다.
        print("   [입력 오류] 수입은 'income', 지출은 'expense'로만 입력할 수 있습니다.")


# [1차 설명]: 등록된 카테고리 명단 중에서 하나를 선택하도록 유도하는 함수입니다.
# [2차 설명]: valid_categories는 '사용 가능한 진짜 카테고리 목록(식비, 교통 등)'이 담긴 리스트 상자입니다.
def prompt_category(valid_categories: List[str]) -> str:
    # [1차 설명]: 카테고리 목록 리스트를 쉼표로 연결한 예쁜 문자열로 만듭니다.
    # [2차 설명]: ", ".join(...)은 리스트 안에 든 단어들 사이에 쉼표를 쏙쏙 끼워 넣어서 "식비, 교통, 주거" 한 줄 글로 만들어주는 함수입니다.
    cats_display = ", ".join(valid_categories)
    # [1차 설명]: 등록된 카테고리를 고를 때까지 반복합니다.
    # [2차 설명]: 없는 카테고리를 적었을 때 계속 다시 물어보기 위한 반복문입니다.
    while True:
        # [1차 설명]: 현재 선택 가능한 카테고리 목록을 화면에 보여줍니다.
        # [2차 설명]: 손님이 무슨 카테고리가 있는지 눈으로 보고 고를 수 있게 보기 목록을 출력합니다.
        print(f"   (등록된 카테고리: {cats_display})")
        # [1차 설명]: 카테고리 이름을 입력받아 공백을 잘라냅니다.
        # [2차 설명]: 손님이 키보드로 친 카테고리 글자를 val 변수에 담습니다.
        val = input("3. 카테고리: ").strip()
        # [1차 설명]: 입력한 카테고리가 진짜 등록된 명단 안에 들어있는지 확인합니다.
        # [2차 설명]: in valid_categories는 명단에 있는 진짜 카테고리인지 대조하는 비교 연산입니다.
        if val in valid_categories:
            # [1차 설명]: 확인된 카테고리 이름을 반환하고 함수를 마칩니다.
            # [2차 설명]: 합격한 카테고리 이름을 호출자에게 돌려줍니다.
            return val
        # [1차 설명]: 명단에 없는 엉뚱한 카테고리를 썼을 때 오류를 안내합니다.
        # [2차 설명]: "등록되지 않은 카테고리입니다"라고 알려주고 다시 맨 위로 올라가 묻습니다.
        print(f"   [입력 오류] '{val}'은(는) 등록되지 않은 카테고리입니다.")


# [1차 설명]: 0보다 큰 양의 정수 금액을 입력받는 함수입니다.
# [2차 설명]: prompt_amount는 지갑에서 실제로 꺼내 쓴 돈 액수를 물어보는 질문 창구입니다.
def prompt_amount() -> int:
    # [1차 설명]: 올바른 숫자를 적을 때까지 반복합니다.
    # [2차 설명]: 글자를 쓰거나 마이너스 돈을 썼을 때 다시 입력받기 위한 루프입니다.
    while True:
        # [1차 설명]: 키보드로 입력을 받고 공백을 자른 뒤, 천 단위 쉼표(,)를 모두 빈칸으로 지웁니다.
        # [2차 설명]: .replace(",", "")는 손님이 "12,000" 처럼 쉼표를 찍었을 때 파이썬이 숫자로 바꿀 수 있게 쉼표를 싹 지워주는 함수입니다.
        val = input("4. 금액 (양수 정수): ").strip().replace(",", "")
        # [1차 설명]: 글자를 정수 숫자로 변환할 수 있는지 검사를 시도합니다.
        # [2차 설명]: 문자가 섞여 있으면 int() 변환에서 에러가 터지므로 try로 감쌉니다.
        try:
            # [1차 설명]: 문자열을 정수(Integer) 숫자로 변환합니다.
            # [2차 설명]: int("12000")은 글자 "12000"을 컴퓨터가 계산할 수 있는 진짜 숫자 12000으로 바꾸는 함수입니다.
            num = int(val)
            # [1차 설명]: 금액 숫자가 0보다 큰 양수인지 확인합니다.
            # [2차 설명]: num > 0은 1원 이상의 진짜 돈인지 검사하는 조건문입니다.
            if num > 0:
                # [1차 설명]: 올바른 양수 금액이면 숫자를 돌려주고 함수를 끝냅니다.
                # [2차 설명]: 검증된 숫자 금액을 반환합니다.
                return num
            # [1차 설명]: 0원이나 마이너스 금액을 적었을 때 안내합니다.
            # [2차 설명]: "금액은 0보다 큰 양수여야 합니다"라고 출력합니다.
            print("   [입력 오류] 금액은 0보다 큰 양수 정수여야 합니다.")
        # [1차 설명]: "abc" 처럼 숫자가 아닌 글자를 적어 int 변환에 실패했을 때 처리합니다.
        # [2차 설명]: 글자가 섞여 있어 숫자로 바꿀 수 없을 때 에러를 잡는 예외 처리입니다.
        except ValueError:
            # [1차 설명]: 숫자 형태로만 적으라고 안내합니다.
            # [2차 설명]: "숫자 형태로만 입력해 주세요"라고 친절히 안내합니다.
            print("   [입력 오류] 숫자 형태로만 입력해 주세요.")


# [1차 설명]: 추가 메모를 입력받는 함수입니다 (선택 사항).
# [2차 설명]: prompt_memo는 "점심 김치찌개 친구랑 더치페이" 같은 부가 설명을 적는 창구입니다.
def prompt_memo() -> str:
    # [1차 설명]: 입력을 받아 공백을 제거한 글자를 그대로 반환합니다.
    # [2차 설명]: 손님이 아무것도 안 적고 그냥 엔터를 치면 빈 문자열("")이 그대로 넘어갑니다.
    return input("5. 메모 (선택 사항, 없으면 Enter): ").strip()


# [1차 설명]: 쉼표로 구분된 태그 단어들을 입력받아 리스트로 쪼개주는 함수입니다.
# [2차 설명]: prompt_tags는 영수증에 ["외식", "점심"] 같은 검색용 꼬리표를 달아두는 창구입니다.
def prompt_tags() -> List[str]:
    # [1차 설명]: 키보드로 태그 문자열을 입력받아 공백을 정리합니다.
    # [2차 설명]: "점심, 외식" 처럼 손님이 친 한 줄 글자를 받습니다.
    val = input("6. 태그 (선택 사항, 쉼표로 구분 예: 점심,외식): ").strip()
    # [1차 설명]: 아무것도 안 적고 그냥 엔터를 쳤는지 확인합니다.
    # [2차 설명]: not val은 입력한 글자가 텅 비어있다는 뜻입니다.
    if not val:
        # [1차 설명]: 아무것도 없으면 빈 리스트([])를 돌려줍니다.
        # [2차 설명]: 태그가 없으므로 빈 바구니를 반환합니다.
        return []
    # [1차 설명]: 쉼표(,)를 기준으로 글자를 자르고 각 단어의 공백을 제거하여 리스트로 만듭니다.
    # [2차 설명]: val.split(",")는 쉼표를 가위 삼아 단어를 싹둑 자르고, t.strip()으로 빈칸을 다듬어 리스트로 모으는 리스트 내포 문법입니다.
    return [t.strip() for t in val.split(",") if t.strip()]


# =====================================================================
# CLI 메인 접수처 실행 함수
# =====================================================================

# [1차 설명]: 어떤 에러가 터져도 에어백이 안전하게 받아내도록 데코레이터를 장착합니다.
# [2차 설명]: @handle_cli_errors는 이 함수 아래에서 무슨 실수가 나든 무서운 영어 에러 대신 친절한 한국어 안내를 띄워주는 안전장치입니다.
@handle_cli_errors
def run_cli() -> None:
    # [1차 설명]: 명령줄 인자 해석기(메인 메뉴판) 객체를 생성합니다.
    # [2차 설명]: ArgumentParser는 손님이 터미널에 적은 명령어(add, list 등)를 분석해 주는 똑똑한 접수대 기계입니다.
    parser = argparse.ArgumentParser(
        # [1차 설명]: 프로그램의 이름을 지정합니다.
        # [2차 설명]: prog는 프로그램의 약자로, 도움말을 띄울 때 맨 위에 찍힐 이름입니다.
        prog="budget_app",
        # [1차 설명]: 프로그램에 대한 간략한 설명을 적어둡니다.
        # [2차 설명]: description은 도움말 창에 출력될 가계부 프로그램 소개글입니다.
        description="콘솔 가계부 애플리케이션 (Python 3.10+)"
    )
    # [1차 설명]: 데이터 저장 폴더를 변경할 수 있는 선택 옵션을 등록합니다.
    # [2차 설명]: add_argument는 손님이 터미널에서 '--data-dir ./mydata' 처럼 저장 폴더를 바꿀 수 있게 옵션 구멍을 뚫어두는 일입니다.
    parser.add_argument(
        # [1차 설명]: 옵션 이름입니다.
        "--data-dir",
        # [1차 설명]: 손님이 옵션을 안 적었을 때 쓸 기본값 폴더입니다.
        # [2차 설명]: 아무것도 안 적으면 현재 폴더 아래의 './data' 폴더를 쓰겠다는 뜻입니다.
        default="./data",
        # [1차 설명]: 이 옵션이 무슨 역할을 하는지 도움말 설명을 적습니다.
        help="데이터 파일 저장 디렉터리 경로 (기본값: ./data)"
    )

    # [1차 설명]: 세부 하위 명령어(서브커맨드)들을 관리할 서브파서 관리자를 만듭니다.
    # [2차 설명]: add_subparsers는 add, list, search 처럼 손님이 고를 수 있는 10가지 세부 메뉴판을 꽂아둘 수 있는 메뉴판 거치대입니다.
    subparsers = parser.add_subparsers(dest="command", help="실행할 명령어")

    # [1차 설명]: 1번째 메뉴인 'add'(거래 추가) 명령어를 등록합니다.
    # [2차 설명]: 손님이 터미널에 'add'라고 치면 대화형으로 질문을 던져 거래를 추가하도록 메뉴판에 등록합니다.
    subparsers.add_parser("add", help="대화형으로 새로운 거래 내역을 추가합니다.")

    # [1차 설명]: 2번째 메뉴인 'list'(목록 조회) 명령어를 등록합니다.
    # [2차 설명]: list_parser는 최신 거래 목록을 보여주는 전용 메뉴판입니다.
    list_parser = subparsers.add_parser("list", help="최신 거래 내역 목록을 조회합니다.")
    # [1차 설명]: 몇 개까지 출력할지 지정하는 --limit 옵션을 추가합니다.
    # [2차 설명]: type=int는 숫자로 받겠다는 뜻이고, default=10은 안 적으면 기본으로 10개만 보여주겠다는 뜻입니다.
    list_parser.add_argument("--limit", type=int, default=10, help="출력할 최대 거래 개수 (기본값: 10)")

    # [1차 설명]: 3번째 메뉴인 'search'(검색) 명령어를 등록합니다.
    # [2차 설명]: search_parser는 조건에 맞는 거래를 찾아주는 검색 전용 메뉴판입니다.
    search_parser = subparsers.add_parser("search", help="다양한 조건으로 거래 내역을 검색합니다.")
    # [1차 설명]: 검색 시작 날짜 옵션(--from)을 추가합니다.
    # [2차 설명]: dest="from_date"는 파이썬 예약어인 from과 충돌하지 않도록 변수 이름을 from_date로 저장하라는 뜻입니다.
    search_parser.add_argument("--from", dest="from_date", help="검색 시작일 (YYYY-MM-DD)")
    # [1차 설명]: 검색 종료 날짜 옵션(--to)을 추가합니다.
    # [2차 설명]: dest="to_date"는 변수 이름을 to_date로 저장하라는 뜻입니다.
    search_parser.add_argument("--to", dest="to_date", help="검색 종료일 (YYYY-MM-DD)")
    # [1차 설명]: 카테고리 일치 검색 옵션(--category)을 추가합니다.
    # [2차 설명]: "식비"만 쓴 내역을 모아보고 싶을 때 쓰는 옵션입니다.
    search_parser.add_argument("--category", help="카테고리 일치 검색")
    # [1차 설명]: 수입인지 지출인지 구분하는 타입 옵션(--type)을 추가합니다.
    # [2차 설명]: choices는 정해진 단어("income", "expense") 둘 중 하나만 들어오게 제한하는 옵션입니다.
    search_parser.add_argument("--type", choices=["income", "expense"], help="거래 타입")
    # [1차 설명]: 메모 키워드 검색 옵션(--q)을 추가합니다.
    # [2차 설명]: dest="keyword"는 검색어 단어를 keyword 변수에 담으라는 뜻입니다.
    search_parser.add_argument("--q", dest="keyword", help="메모 검색 키워드")
    # [1차 설명]: 특정 태그 포함 검색 옵션(--tag)을 추가합니다.
    # [2차 설명]: "외식" 태그가 달린 것만 찾고 싶을 때 쓰는 옵션입니다.
    search_parser.add_argument("--tag", help="특정 태그 포함 여부")

    # [1차 설명]: 4번째 메뉴인 'delete'(삭제) 명령어를 등록합니다.
    # [2차 설명]: del_parser는 잘못 적은 거래 영수증을 파기하는 전용 메뉴판입니다.
    del_parser = subparsers.add_parser("delete", help="거래 내역을 삭제합니다.")
    # [1차 설명]: 삭제할 대상 거래의 고유 ID를 필수로 받습니다.
    # [2차 설명]: required=True는 이 옵션을 안 적으면 명령어가 실행되지 않고 오류를 내는 필수 옵션이라는 뜻입니다.
    del_parser.add_argument("--id", required=True, help="삭제할 거래 ID")

    # [1차 설명]: 5번째 메뉴인 'update'(수정) 명령어를 등록합니다.
    # [2차 설명]: update_parser는 영수증 내용을 고쳐 적는 전용 메뉴판입니다.
    update_parser = subparsers.add_parser("update", help="거래 내역을 수정합니다.")
    # [1차 설명]: 수정할 대상 거래의 고유 ID를 필수로 받습니다.
    # [2차 설명]: 어느 영수증을 고칠지 알아야 하므로 ID를 필수로 요구합니다.
    update_parser.add_argument("--id", required=True, help="수정할 대상 거래 ID")
    # [1차 설명]: 새로 바꿀 날짜 옵션을 추가합니다.
    # [2차 설명]: --date 2026-06-01 처럼 영수증의 발생 날짜를 고쳐 적고 싶을 때 사용하는 선택 옵션입니다.
    update_parser.add_argument("--date", help="새로운 날짜 (YYYY-MM-DD)")
    # [1차 설명]: 새로 바꿀 수입/지출 타입 옵션을 추가합니다.
    # [2차 설명]: choices로 수입(income)이나 지출(expense) 둘 중 하나만 들어오도록 오타를 막아주는 선택 옵션입니다.
    update_parser.add_argument("--type", choices=["income", "expense"], help="새로운 거래 타입")
    # [1차 설명]: 새로 바꿀 카테고리 옵션을 추가합니다.
    # [2차 설명]: --category 카페 처럼 다른 항목으로 영수증 분류를 변경할 때 쓰는 옵션입니다.
    update_parser.add_argument("--category", help="새로운 카테고리")
    # [1차 설명]: 새로 바꿀 금액 옵션을 추가합니다.
    # [2차 설명]: type=int로 숫자로만 받으며 잘못 적힌 지출액을 올바른 액수로 덮어쓸 때 쓰는 옵션입니다.
    update_parser.add_argument("--amount", type=int, help="새로운 금액 (양수 정수)")
    # [1차 설명]: 새로 바꿀 메모 옵션을 추가합니다.
    # [2차 설명]: --memo "스타벅스 라떼" 처럼 덧붙인 메모 설명을 수정할 때 쓰는 옵션입니다.
    update_parser.add_argument("--memo", help="새로운 메모")
    # [1차 설명]: 새로 바꿀 태그 목록 옵션을 추가합니다.
    # [2차 설명]: --tags "커피,간식" 처럼 검색용 꼬리표들을 통째로 새로 바꿀 때 쓰는 옵션입니다.
    update_parser.add_argument("--tags", help="새로운 태그 (쉼표로 구분)")

    # [1차 설명]: 6번째 메뉴인 'category'(카테고리 관리) 명령어를 등록합니다.
    # [2차 설명]: 카테고리 목록 보기, 추가하기, 삭제하기를 묶어서 관리하는 메뉴판입니다.
    cat_parser = subparsers.add_parser("category", help="카테고리를 관리합니다.")
    # [1차 설명]: category 명령어 내부의 세부 동작(list, add, remove)을 관리할 서브파서를 만듭니다.
    # [2차 설명]: add_subparsers를 써서 category 뒤에 올 두 번째 세부 명령을 분류합니다.
    cat_sub = cat_parser.add_subparsers(dest="category_action", help="카테고리 작업 선택")
    # [1차 설명]: 카테고리 목록 보기 메뉴를 등록합니다.
    # [2차 설명]: 'category list'를 치면 현재 사용 가능한 카테고리들을 나열합니다.
    cat_sub.add_parser("list", help="전체 카테고리 목록을 확인합니다.")
    # [1차 설명]: 새 카테고리 추가 메뉴를 등록합니다.
    # [2차 설명]: 'category add 취미' 처럼 새 항목을 장부에 등록하는 메뉴판입니다.
    cat_add = cat_sub.add_parser("add", help="새로운 카테고리를 추가합니다.")
    # [1차 설명]: 추가할 카테고리 이름을 필수 위치 인자로 받습니다.
    # [2차 설명]: 대시(--) 없이 바로 이름 글자를 적게 하는 위치 인자(Positional Argument)입니다.
    cat_add.add_argument("name", help="추가할 카테고리 이름")
    # [1차 설명]: 카테고리 삭제 메뉴를 등록합니다.
    # [2차 설명]: 'category remove 유흥' 처럼 안 쓰는 항목을 장부에서 지우는 메뉴판입니다.
    cat_del = cat_sub.add_parser("remove", help="카테고리를 삭제합니다.")
    # [1차 설명]: 삭제할 카테고리 이름을 필수 위치 인자로 받습니다.
    # [2차 설명]: 삭제할 이름을 직접 적도록 요구하는 위치 인자입니다.
    cat_del.add_argument("name", help="삭제할 카테고리 이름")

    # [1차 설명]: 7번째 메뉴인 'budget'(예산 관리) 명령어를 등록합니다.
    # [2차 설명]: 한 달 예산 목표 카드를 관리하는 메뉴판입니다.
    budget_parser = subparsers.add_parser("budget", help="월별 예산을 관리합니다.")
    # [1차 설명]: budget 내부 세부 동작(set)을 관리할 서브파서를 만듭니다.
    # [2차 설명]: 예산 관련 추가 명령을 붙이기 위한 하위 메뉴판 거치대입니다.
    budget_sub = budget_parser.add_subparsers(dest="budget_action", help="예산 작업 선택")
    # [1차 설명]: 예산 설정 메뉴(set)를 등록합니다.
    # [2차 설명]: 이번 달 쓸 돈 상한선을 정하는 'budget set' 메뉴판입니다.
    b_set = budget_sub.add_parser("set", help="월별 예산을 설정합니다.")
    # [1차 설명]: 예산을 설정할 대상 월(--month)을 필수로 받습니다.
    # [2차 설명]: required=True로 어느 달의 예산인지(YYYY-MM) 반드시 적게 만듭니다.
    b_set.add_argument("--month", required=True, help="설정 대상 월 (YYYY-MM)")
    # [1차 설명]: 설정할 예산 한도 금액(--amount)을 숫자로 필수로 받습니다.
    # [2차 설명]: type=int와 required=True로 목표 금액 숫자를 반드시 입력받습니다.
    b_set.add_argument("--amount", type=int, required=True, help="예산 금액 (양수 정수)")

    # [1차 설명]: 8번째 메뉴인 'summary'(월별 요약 리포트) 명령어를 등록합니다.
    # [2차 설명]: 한 달 동안 번 돈, 쓴 돈, 남은 잔액 성적표를 보여주는 메뉴판입니다.
    sum_parser = subparsers.add_parser("summary", help="월별 요약 리포트를 출력합니다.")
    # [1차 설명]: 조회할 대상 월(--month)을 필수로 받습니다.
    # [2차 설명]: required=True로 2026-05 처럼 조회할 월을 반드시 지정하게 합니다.
    sum_parser.add_argument("--month", required=True, help="조회할 대상 월 (YYYY-MM)")
    # [1차 설명]: 지출 1위부터 몇 위까지 볼지 정하는 --top 옵션을 추가합니다 (기본값 3).
    # [2차 설명]: default=3으로 안 적으면 가장 돈을 많이 쓴 상위 3개 카테고리를 보여줍니다.
    sum_parser.add_argument("--top", type=int, default=3, help="지출 상위 카테고리 수 (기본값: 3)")

    # [1차 설명]: 9번째 메뉴인 'export'(CSV 내보내기) 명령어를 등록합니다.
    # [2차 설명]: 가계부 거래 내역을 엑셀용 CSV 파일로 인쇄해서 저장하는 메뉴판입니다.
    exp_parser = subparsers.add_parser("export", help="조건에 맞는 거래 내역을 CSV 파일로 내보냅니다.")
    # [1차 설명]: 저장할 CSV 파일의 경로(--out)를 필수로 받습니다.
    # [2차 설명]: required=True로 내보낼 파일 이름(예: my_data.csv)을 반드시 적게 합니다.
    exp_parser.add_argument("--out", required=True, help="저장할 CSV 파일 경로 (필수)")
    # [1차 설명]: 내보낼 대상 월(--month) 옵션입니다.
    # [2차 설명]: 특정 월(예: 2026-05)의 거래들만 엑셀로 뽑고 싶을 때 지정합니다.
    exp_parser.add_argument("--month", help="내보낼 대상 월 (YYYY-MM)")
    # [1차 설명]: 내보낼 시작일(--from) 옵션입니다.
    # [2차 설명]: 특정 기간의 시작 날짜를 필터링할 때 사용하는 선택 옵션입니다.
    exp_parser.add_argument("--from", dest="from_date", help="시작일 (YYYY-MM-DD)")
    # [1차 설명]: 내보낼 종료일(--to) 옵션입니다.
    # [2차 설명]: 특정 기간의 끝 날짜를 필터링할 때 사용하는 선택 옵션입니다.
    exp_parser.add_argument("--to", dest="to_date", help="종료일 (YYYY-MM-DD)")

    # [1차 설명]: 10번째 메뉴인 'import'(CSV 가져오기) 명령어를 등록합니다.
    # [2차 설명]: 외부 엑셀 CSV 파일의 거래 내역을 내 가계부로 일괄 흡수하는 메뉴판입니다.
    imp_parser = subparsers.add_parser("import", help="CSV 파일로부터 거래 내역을 일괄 가져옵니다.")
    # [1차 설명]: 읽어올 대상 CSV 파일의 경로(--from)를 필수로 받습니다.
    # [2차 설명]: required=True로 읽어올 외부 엑셀 파일 경로를 반드시 적게 합니다.
    imp_parser.add_argument("--from", dest="input_file", required=True, help="가져올 CSV 파일 경로 (필수)")

    # [1차 설명]: 손님이 터미널에 실제로 입력한 명령어 인자들을 해석하여 객체로 받습니다.
    # [2차 설명]: parse_args()는 손님이 친 글자들을 분석해서 args.command, args.amount 처럼 꺼내 쓰기 쉽게 포장해 주는 실행 명령입니다.
    args = parser.parse_args()

    # [1차 설명]: 아무런 하위 명령어도 입력하지 않고 프로그램 이름만 쳤는지 확인합니다.
    # [2차 설명]: if not args.command는 손님이 메뉴를 안 골랐다는 뜻입니다.
    if not args.command:
        # [1차 설명]: 도움말 안내판을 콘솔 화면에 출력합니다.
        # [2차 설명]: "사용법: add, list, search 등을 입력하세요" 하고 안내판을 보여줍니다.
        parser.print_help()
        # [1차 설명]: 프로그램을 정상적으로 종료 코드 0으로 마칩니다.
        # [2차 설명]: 손님이 메뉴만 확인했으므로 오류 없이 깨끗하게 종료합니다.
        sys.exit(0)

    # [1차 설명]: 장부 보관소 창고지기 객체를 생성합니다.
    # [2차 설명]: args.data_dir 경로의 서랍을 관리할 창고지기를 출근시킵니다.
    repo = FileRepository(data_dir=args.data_dir)
    # [1차 설명]: 핵심 계산과 규칙을 처리하는 회계사 객체를 생성하고 창고지기를 연결합니다.
    # [2차 설명]: 창고지기와 손발을 맞출 수석 회계사를 카운터 뒤에 앉힙니다.
    service = BudgetService(repo=repo)

    # [1차 설명]: 손님이 고른 명령어가 'add'(거래 추가)인 경우입니다.
    # [2차 설명]: elif가 아닌 if로 시작하여 1번째 메뉴 분기를 탑니다.
    if args.command == "add":
        # [1차 설명]: 거래 추가 시작 안내선을 예쁘게 출력합니다.
        # [2차 설명]: print()는 모니터 화면에 글자나 선을 찍어주는 출력 도구입니다. 구분선을 그어 화면을 깔끔하게 정리합니다.
        print("========================================")
        # [1차 설명]: 메뉴 제목을 출력합니다.
        # [2차 설명]: 손님이 지금 무슨 작업을 하고 있는지 알 수 있도록 "새로운 거래 내역 추가" 제목을 화면 중앙에 보여줍니다.
        print("         새로운 거래 내역 추가          ")
        # [1차 설명]: 하단 안내선을 출력합니다.
        # [2차 설명]: 제목 글자 아래에 닫는 구분선을 그어 제목 상자를 완성합니다.
        print("========================================")
        # [1차 설명]: 날짜를 물어봐서 tx_date 변수에 받습니다.
        # [2차 설명]: prompt_date() 함수를 호출하여 손님에게 날짜(YYYY-MM-DD)를 입력받고, 검증된 날짜 글자를 tx_date 바구니에 담아둡니다.
        tx_date = prompt_date()
        # [1차 설명]: 수입인지 지출인지 물어봐서 tx_type 변수에 받습니다.
        # [2차 설명]: prompt_type() 함수를 호출하여 수입(income)인지 지출(expense)인지 물어보고, 그 결과를 tx_type 바구니에 보관합니다.
        tx_type = prompt_type()
        # [1차 설명]: 등록된 카테고리를 보여주며 물어봐서 tx_category 변수에 받습니다.
        # [2차 설명]: repo.load_categories()로 창고에서 현재 카테고리 명단(식비, 교통 등)을 꺼내온 뒤, prompt_category에 넘겨 손님이 명단 중에서 고르게 유도하고 결과를 tx_category에 담습니다.
        tx_category = prompt_category(repo.load_categories())
        # [1차 설명]: 금액 숫자를 물어봐서 tx_amount 변수에 받습니다.
        # [2차 설명]: prompt_amount() 함수를 호출하여 손님이 쓴 돈 액수를 묻고, 0보다 큰 양의 정수 숫자로 변환된 값을 tx_amount 바구니에 담습니다.
        tx_amount = prompt_amount()
        # [1차 설명]: 메모를 물어봐서 tx_memo 변수에 받습니다.
        # [2차 설명]: prompt_memo() 함수를 호출하여 영수증에 덧붙일 메모 글자("점심 김치찌개" 등)를 입력받아 tx_memo 바구니에 보관합니다.
        tx_memo = prompt_memo()
        # [1차 설명]: 태그 단어들을 물어봐서 tx_tags 변수에 받습니다.
        # [2차 설명]: prompt_tags() 함수를 호출하여 쉼표로 구분된 꼬리표 단어들을 받아 ['점심', '외식'] 형태의 리스트 목록으로 tx_tags에 저장합니다.
        tx_tags = prompt_tags()

        # [1차 설명]: 수집한 정보로 회계사에게 새 거래를 생성해 장부에 적어달라고 요청하고 발급된 ID를 받습니다.
        # [2차 설명]: create_transaction 함수가 8자리 번호표를 만들어 장부에 적고 새 ID를 new_id에 돌려줍니다.
        new_id = service.create_transaction(
            date_str=tx_date,
            tx_type=tx_type,
            category=tx_category,
            amount=tx_amount,
            memo=tx_memo,
            tags=tx_tags
        )
        # [1차 설명]: 완료 구분선을 출력합니다.
        # [2차 설명]: 작업이 끝났음을 알리기 위해 구분선을 출력합니다.
        print("========================================")
        # [1차 설명]: 저장 성공 축하 메시지를 출력합니다.
        # [2차 설명]: 손님에게 거래 내역이 장부에 정상적으로 기록되었음을 체크 표시(✔)와 함께 안심시켜 줍니다.
        print("✔ 거래가 성공적으로 저장되었습니다.")
        # [1차 설명]: 발급된 8자리 고유 번호표를 손님 모니터에 보여줍니다.
        # [2차 설명]: f-string(f"...")을 써서 방금 회계사가 발급한 8자리 주민번호 같은 고유 ID(new_id)를 글자 사이에 쏙 넣어 화면에 출력합니다.
        print(f"✔ 생성된 거래 ID: {new_id}")
        # [1차 설명]: 닫는 구분선을 출력합니다.
        # [2차 설명]: 거래 추가 화면을 깔끔하게 마무리 짓는 닫는 선을 그어줍니다.
        print("========================================")

    # [1차 설명]: 손님이 고른 명령어가 'list'(목록 조회)인 경우입니다.
    # [2차 설명]: elif는 '그게 아니고 만약에'라는 뜻으로 2번째 분기를 탑니다.
    elif args.command == "list":
        # [1차 설명]: 회계사에게 최신 거래 내역을 지정한 개수(args.limit)만큼 뽑아달라고 요청합니다.
        # [2차 설명]: list_transactions 함수가 최신순으로 정렬된 영수증 리스트를 results 변수에 돌려줍니다.
        results = service.list_transactions(limit=args.limit)
        # [1차 설명]: 장부에 거래가 1건도 없어서 빈 리스트인지 확인합니다.
        # [2차 설명]: not results는 영수증이 하나도 없다는 뜻입니다.
        if not results:
            # [1차 설명]: 조회할 내역이 없다고 손님에게 알립니다.
            print("조회할 거래 내역이 없습니다.")
            # [1차 설명]: 함수 실행을 여기서 마치고 나갑니다.
            return

        # [1차 설명]: 목록 제목과 최대 몇 건인지 출력합니다.
        # [2차 설명]: print()를 사용해 손님이 한눈에 알아볼 수 있도록 "=== 최신 거래 내역 ===" 안내 머리글을 모니터에 찍어줍니다.
        print(f"\n=== 최신 거래 내역 (최대 {args.limit}건) ===")
        # [1차 설명]: 표의 열 제목(헤더)을 고정폭으로 예쁘게 줄 맞춰 출력합니다.
        # [2차 설명]: {'ID':<10}은 10칸 공간을 잡고 왼쪽 정렬, {'금액':>10}은 오른쪽 정렬하여 엑셀 표처럼 깔끔하게 줄을 맞춰주는 서식 출력입니다.
        print(f"{'ID':<10} {'날짜':<12} {'구분':<8} {'카테고리':<10} {'금액':>10}원  {'메모'} (태그)")
        # [1차 설명]: 표 구분선을 75칸 출력합니다.
        # [2차 설명]: "-" * 75 연산으로 대시(-) 기호를 75개 길게 이어 붙여 표 머리글과 내용물을 구분하는 가로선을 그립니다.
        print("-" * 75)
        # [1차 설명]: 영수증 목록(results)에서 영수증을 1장씩 꺼내며 반복합니다.
        # [2차 설명]: for tx in results 루프를 돌려 바구니에 담긴 거래 영수증(tx)을 한 장씩 차례대로 꺼내어 처리합니다.
        for tx in results:
            # [1차 설명]: 태그가 있으면 "(외식, 점심)" 형태로 예쁘게 묶고 없으면 빈 글자로 둡니다.
            # [2차 설명]: ', '.join(tx.tags)로 태그 단어들을 쉼표로 잇고 괄호로 감싸는 짧은 삼항 연산식입니다.
            tag_str = f"({', '.join(tx.tags)})" if tx.tags else ""
            # [1차 설명]: 영수증의 각 칸(ID, 날짜, 구분, 카테고리, 금액, 메모, 태그)을 표 형식으로 한 줄씩 출력합니다.
            # [2차 설명]: {tx.amount:>10,}는 금액 숫자에 천 단위 쉼표를 찍고 10칸 오른쪽 정렬하여 장부 줄을 반듯하게 맞춥니다.
            print(f"{tx.id:<10} {tx.date:<12} {tx.type:<8} {tx.category:<10} {tx.amount:>10,}원  {tx.memo} {tag_str}")
        # [1차 설명]: 표 닫는 선을 출력합니다.
        # [2차 설명]: 표 출력이 끝났음을 알리는 75칸 가로 마감선을 그어줍니다.
        print("-" * 75)

    # [1차 설명]: 손님이 고른 명령어가 'search'(검색)인 경우입니다.
    # [2차 설명]: 손님이 입력한 여러 필터 조건으로 검색하는 3번째 분기입니다.
    elif args.command == "search":
        # [1차 설명]: 회계사에게 시작일, 종료일, 카테고리, 타입, 키워드, 태그 조건을 넘겨 검색을 요청합니다.
        # [2차 설명]: service.search_transactions 함수가 전달받은 조건들에 맞는 영수증만 쏙쏙 골라내어 results 리스트에 담아줍니다.
        results = service.search_transactions(
            from_date=args.from_date,
            to_date=args.to_date,
            category=args.category,
            tx_type=args.type,
            keyword=args.keyword,
            tag=args.tag
        )
        # [1차 설명]: 검색 조건에 맞는 영수증이 1건도 없는지 확인합니다.
        # [2차 설명]: if not results는 회계사가 찾아온 영수증 리스트가 텅 비어있다는 뜻입니다.
        if not results:
            # [1차 설명]: 일치하는 거래가 없다고 안내합니다.
            # [2차 설명]: 손님에게 조건에 맞는 영수증을 찾지 못했다고 친절히 안내 문구를 띄웁니다.
            print("검색 조건과 일치하는 거래 내역이 없습니다.")
            # [1차 설명]: 검색 작업을 마칩니다.
            # [2차 설명]: return으로 함수를 즉시 종료하여 불필요한 아래 코드를 실행하지 않습니다.
            return

        # [1차 설명]: 총 몇 건이 검색되었는지 제목을 출력합니다.
        # [2차 설명]: len(results)로 찾은 영수증 개수를 세어 "거래 검색 결과 (총 N건)" 형태로 제목을 보여줍니다.
        print(f"\n=== 거래 검색 결과 (총 {len(results)}건) ===")
        # [1차 설명]: 표 헤더를 출력합니다.
        # [2차 설명]: 각 열의 이름(ID, 날짜, 구분 등)을 일정한 간격으로 줄 맞춰 출력합니다.
        print(f"{'ID':<10} {'날짜':<12} {'구분':<8} {'카테고리':<10} {'금액':>10}원  {'메모'} (태그)")
        # [1차 설명]: 표 구분선을 출력합니다.
        # [2차 설명]: "-" * 75로 표 머리글 아래에 가로 구분선을 그립니다.
        print("-" * 75)
        # [1차 설명]: 검색된 영수증들을 한 장씩 순회합니다.
        # [2차 설명]: 찾은 영수증 바구니(results)에서 영수증(tx)을 1장씩 순서대로 꺼냅니다.
        for tx in results:
            # [1차 설명]: 태그가 있으면 괄호로 묶고 없으면 빈 문자열을 만듭니다.
            # [2차 설명]: if tx.tags 조건으로 태그 유무를 검사해 예쁜 모양으로 다듬습니다.
            tag_str = f"({', '.join(tx.tags)})" if tx.tags else ""
            # [1차 설명]: 검색된 영수증 1행을 화면에 찍어줍니다.
            # [2차 설명]: 고유번호, 날짜, 수입/지출, 카테고리, 쉼표 찍힌 금액, 메모를 한 줄에 반듯하게 출력합니다.
            print(f"{tx.id:<10} {tx.date:<12} {tx.type:<8} {tx.category:<10} {tx.amount:>10,}원  {tx.memo} {tag_str}")
        # [1차 설명]: 표 닫는 선을 출력합니다.
        # [2차 설명]: 검색 결과 표 마감을 알리는 가로선을 그어줍니다.
        print("-" * 75)

    # [1차 설명]: 손님이 고른 명령어가 'delete'(삭제)인 경우입니다.
    # [2차 설명]: 지정한 ID 영수증을 장부에서 파기하는 4번째 분기입니다.
    elif args.command == "delete":
        # [1차 설명]: 회계사에게 대상 ID 영수증을 삭제해 달라고 부탁하고 성공 여부(True/False)를 받습니다.
        # [2차 설명]: service.delete_transaction 함수가 장부를 뒤져 해당 ID를 지우고, 성공하면 True를 success에 넘겨줍니다.
        success = service.delete_transaction(tx_id=args.id)
        # [1차 설명]: 삭제가 성공했는지 확인합니다.
        # [2차 설명]: if success는 삭제 결과가 성공(True)인지 검사하는 조건문입니다.
        if success:
            # [1차 설명]: 성공 메시지를 출력합니다.
            # [2차 설명]: 장부에서 영수증이 깔끔히 파기되었음을 손님에게 초록 체크 표시와 함께 알려줍니다.
            print(f"✔ 거래 ID '{args.id}' 내역이 성공적으로 삭제되었습니다.")
        # [1차 설명]: 장부에 그런 ID가 없어서 삭제에 실패한 경우입니다.
        # [2차 설명]: else는 지우려는 번호표가 장부에 없을 때 실행되는 예외 안내 분기입니다.
        else:
            # [1차 설명]: 존재하지 않는 데이터라고 안내합니다.
            # [2차 설명]: 손님에게 해당 ID의 거래를 찾을 수 없으니 번호를 다시 확인하라고 안내합니다.
            print(f"[안내] ID '{args.id}'에 해당하는 거래 데이터가 존재하지 않습니다.")

    # [1차 설명]: 손님이 고른 명령어가 'update'(수정)인 경우입니다.
    # [2차 설명]: 영수증의 날짜나 금액을 고쳐 적는 5번째 분기입니다.
    elif args.command == "update":
        # [1차 설명]: 손님이 새 태그를 옵션으로 줬다면 쉼표로 잘라 리스트로 만들고, 안 줬으면 None으로 둡니다.
        # [2차 설명]: args.tags 문자열이 있으면 split(',')으로 쪼개고 strip()으로 다듬어 tags_list에 담고, 없으면 그대로 None을 유지합니다.
        tags_list = [t.strip() for t in args.tags.split(",") if t.strip()] if args.tags else None
        # [1차 설명]: 회계사에게 변경할 필드 값들을 넘겨 수정을 요청하고 성공 여부를 받습니다.
        # [2차 설명]: service.update_transaction 함수가 장부에서 해당 ID를 찾아 새 날짜, 금액, 메모 등으로 덮어쓰고 결과를 success에 돌려줍니다.
        success = service.update_transaction(
            tx_id=args.id,
            date_str=args.date,
            tx_type=args.type,
            category=args.category,
            amount=args.amount,
            memo=args.memo,
            tags=tags_list
        )
        # [1차 설명]: 수정이 성공했는지 확인합니다.
        # [2차 설명]: if success는 수정 작업이 성공(True)했는지 확인하는 조건문입니다.
        if success:
            # [1차 설명]: 수정 성공 메시지를 출력합니다.
            # [2차 설명]: 영수증 내용이 올바르게 고쳐졌음을 손님 모니터에 안내합니다.
            print(f"✔ 거래 ID '{args.id}' 내역이 성공적으로 수정되었습니다.")
        # [1차 설명]: 해당 ID가 장부에 없어서 수정에 실패한 경우입니다.
        # [2차 설명]: else는 고치려는 번호표가 장부에 존재하지 않을 때 실행됩니다.
        else:
            # [1차 설명]: 존재하지 않는 데이터라고 안내합니다.
            # [2차 설명]: 영수증 번호가 맞지 않다고 친절히 손님에게 알려줍니다.
            print(f"[안내] ID '{args.id}'에 해당하는 거래 데이터가 존재하지 않습니다.")

    # [1차 설명]: 손님이 고른 명령어가 'category'(카테고리 관리)인 경우입니다.
    # [2차 설명]: 카테고리 목록/추가/삭제를 다루는 6번째 분기입니다.
    elif args.command == "category":
        # [1차 설명]: category 뒤에 세부 작업(list, add, remove)을 안 적었는지 확인합니다.
        # [2차 설명]: if not args.category_action은 세부 동작 메뉴를 선택하지 않았다는 뜻입니다.
        if not args.category_action:
            # [1차 설명]: 카테고리 도움말을 보여주고 끝냅니다.
            # [2차 설명]: cat_parser.print_help()로 카테고리 사용법 안내판을 화면에 띄웁니다.
            cat_parser.print_help()
            # [1차 설명]: 함수 실행을 여기서 마칩니다.
            # [2차 설명]: return을 실행하여 아래 코드로 넘어가지 않고 즉시 종료합니다.
            return

        # [1차 설명]: 세부 작업이 'list'(목록 보기)인 경우입니다.
        # [2차 설명]: if args.category_action == 'list'는 등록된 카테고리 명단을 요청했을 때 실행됩니다.
        if args.category_action == "list":
            # [1차 설명]: 회계사에게 카테고리 목록을 받아옵니다.
            # [2차 설명]: service.list_categories()가 창고에서 꺼낸 카테고리 이름 목록(식비, 교통 등)을 categories 변수에 담아줍니다.
            categories = service.list_categories()
            # [1차 설명]: 목록 제목을 출력합니다.
            # [2차 설명]: print()로 카테고리 목록의 시작을 알리는 제목을 화면에 보여줍니다.
            print("\n=== 등록된 카테고리 목록 ===")
            # [1차 설명]: 번호를 1번부터 매겨가며 카테고리 이름을 하나씩 출력합니다.
            # [2차 설명]: enumerate(categories, 1)로 1번, 2번, 3번 순번표를 달아가며 카테고리 이름(c)을 한 줄씩 찍어줍니다.
            for idx, c in enumerate(categories, 1):
                print(f"{idx}. {c}")
            # [1차 설명]: 구분선을 출력합니다.
            # [2차 설명]: "-" * 30 연산으로 30칸 가로선을 그어 목록을 깔끔하게 마감합니다.
            print("-" * 30)

        # [1차 설명]: 세부 작업이 'add'(추가하기)인 경우입니다.
        # [2차 설명]: elif는 세부 작업이 'add'일 때 새 카테고리를 등록하는 분기입니다.
        elif args.category_action == "add":
            # [1차 설명]: 회계사에게 새 카테고리 이름을 추가해 달라고 요청합니다.
            # [2차 설명]: service.add_category 함수가 중복 여부를 검사한 뒤 categories.json 장부에 새 이름을 적어 넣습니다.
            service.add_category(name=args.name)
            # [1차 설명]: 추가 성공 메시지를 출력합니다.
            # [2차 설명]: 새 카테고리가 장부에 안전하게 추가되었음을 손님에게 알려줍니다.
            print(f"✔ 카테고리 '{args.name}'이(가) 성공적으로 추가되었습니다.")

        # [1차 설명]: 세부 작업이 'remove'(삭제하기)인 경우입니다.
        # [2차 설명]: elif는 세부 작업이 'remove'일 때 카테고리를 명단에서 지우는 분기입니다.
        elif args.category_action == "remove":
            # [1차 설명]: 회계사에게 해당 카테고리 삭제를 요청합니다 (사용 중이면 회계사가 거절 에러를 던집니다).
            # [2차 설명]: service.remove_category 함수가 기존 거래에서 쓰고 있는지 검사한 후 안전하게 명단에서 제거합니다.
            service.remove_category(name=args.name)
            # [1차 설명]: 삭제 성공 메시지를 출력합니다.
            # [2차 설명]: 카테고리가 정상적으로 삭제되었음을 손님에게 알려줍니다.
            print(f"✔ 카테고리 '{args.name}'이(가) 성공적으로 삭제되었습니다.")

    # [1차 설명]: 손님이 고른 명령어가 'budget'(예산 관리)인 경우입니다.
    # [2차 설명]: 한 달 목표 예산 카드를 관리하는 7번째 분기입니다.
    elif args.command == "budget":
        # [1차 설명]: 세부 작업이 'set'(설정하기)인 경우입니다.
        # [2차 설명]: if args.budget_action == 'set'은 이번 달 쓸 돈 상한선을 정하겠다는 뜻입니다.
        if args.budget_action == "set":
            # [1차 설명]: 회계사에게 대상 월과 예산 금액 저장을 요청합니다.
            # [2차 설명]: service.set_budget 함수가 budgets.json 장부에 "2026-05월은 500,000원"이라고 목표 카드를 등록합니다.
            service.set_budget(month=args.month, amount=args.amount)
            # [1차 설명]: 예산 설정 성공 메시지를 금액에 쉼표를 찍어 출력합니다.
            # [2차 설명]: 손님에게 해당 월의 예산이 얼마로 잘 잡혔는지 화면에 예쁘게 알려줍니다.
            print(f"✔ {args.month}월 예산이 {args.amount:,}원으로 설정되었습니다.")
        # [1차 설명]: 세부 작업을 안 적었거나 잘못 적은 경우입니다.
        # [2차 설명]: else는 set 명령어를 제대로 적지 않았을 때 실행됩니다.
        else:
            # [1차 설명]: 예산 도움말을 보여줍니다.
            # [2차 설명]: budget_parser.print_help()로 예산 명령어 사용법을 안내합니다.
            budget_parser.print_help()

    # [1차 설명]: 손님이 고른 명령어가 'summary'(월별 요약 리포트)인 경우입니다.
    # [2차 설명]: 한 달 동안 번 돈과 쓴 돈 성적표를 계산해 보여주는 8번째 분기입니다.
    elif args.command == "summary":
        # [1차 설명]: 회계사에게 해당 월의 요약 통계 계산을 요청합니다.
        # [2차 설명]: service.get_monthly_summary 함수가 한 달 치 영수증을 모아 수입 합계, 지출 합계, 남은 잔액, 지출 1~3위를 딕셔너리로 계산해 summary에 넘겨줍니다.
        summary = service.get_monthly_summary(month=args.month, top_n=args.top)

        # [1차 설명]: 그 달에 거래 데이터가 1건도 없어서 결과가 None인지 확인합니다.
        # [2차 설명]: if summary is None은 장부에 영수증이 단 1장도 없어 계산할 내역이 없다는 뜻입니다.
        if summary is None:
            # [1차 설명]: 거래 데이터가 없다고 손님에게 안내합니다.
            # [2차 설명]: 해당 월에 등록된 가계부 내역이 없으니 먼저 거래를 추가하라고 안내합니다.
            print(f"\n[안내] {args.month}월에는 등록된 거래 데이터가 없습니다.")
            # [1차 설명]: 요약 작업을 마칩니다.
            # [2차 설명]: return으로 함수를 종료하여 아래 리포트 출력을 건너뜁니다.
            return

        # [1차 설명]: 요약 리포트 헤더 구분선을 출력합니다.
        # [2차 설명]: 성적표 리포트의 시작을 알리는 40칸 굵은 구분선을 그립니다.
        print(f"\n========================================")
        # [1차 설명]: 리포트 제목(예: 2026-05 가계부 요약 리포트)을 출력합니다.
        # [2차 설명]: 몇 월의 결산 성적표인지 가운데 정렬 느낌으로 제목을 보여줍니다.
        print(f"         {args.month} 가계부 요약 리포트         ")
        # [1차 설명]: 구분선을 출력합니다.
        # [2차 설명]: 제목 아래에 구분선을 그어 머리글 상자를 완성합니다.
        print("========================================")
        # [1차 설명]: 총 수입 합계 금액을 출력합니다.
        # [2차 설명]: summary['income']에 담긴 그 달 번 돈 전체 합계를 쉼표 찍어 출력합니다.
        print(f"• 총 수입 : {summary['income']:>12,}원")
        # [1차 설명]: 총 지출 합계 금액을 출력합니다.
        # [2차 설명]: summary['expense']에 담긴 그 달 쓴 돈 전체 합계를 쉼표 찍어 출력합니다.
        print(f"• 총 지출 : {summary['expense']:>12,}원")
        # [1차 설명]: 통장에 남은 잔액(총수입 - 총지출)을 출력합니다.
        # [2차 설명]: summary['balance']에 담긴 순수 잔여 금액을 계산 공식 안내와 함께 보여줍니다.
        print(f"• 잔   액 : {summary['balance']:>12,}원 (총수입 - 총지출)")
        # [1차 설명]: 중간 구분선을 출력합니다.
        # [2차 설명]: 지출 랭킹 섹션과 나누는 40칸 점선/대시선을 그립니다.
        print(f"----------------------------------------")
        # [1차 설명]: 지출 1위부터 상위 몇 위까지 보여주는지 제목을 출력합니다.
        # [2차 설명]: 손님이 옵션으로 지정한 개수(args.top, 기본 3개)만큼 랭킹 제목을 찍습니다.
        print(f"▶ 지출 카테고리 TOP {args.top}")
        # [1차 설명]: 지출 내역이 하나도 없는지 확인합니다.
        # [2차 설명]: if not summary['top_categories']는 지출 거래가 0건일 때를 확인합니다.
        if not summary["top_categories"]:
            # [1차 설명]: 지출 내역이 없다고 안내합니다.
            # [2차 설명]: 쓴 돈이 없어서 순위를 매길 수 없다고 알려줍니다.
            print("  (지출 내역이 없습니다.)")
        # [1차 설명]: 지출 내역이 있는 경우 순위별로 출력합니다.
        # [2차 설명]: else는 쓴 돈이 있어서 순위 리스트가 존재할 때 실행됩니다.
        else:
            # [1차 설명]: 1위부터 번호를 매겨가며 카테고리 이름과 금액을 출력합니다.
            # [2차 설명]: enumerate(..., 1)로 1위, 2위 순위를 매겨가며 카테고리별 쓴 돈을 정렬하여 보여줍니다.
            for rank, (cat_name, cat_amt) in enumerate(summary["top_categories"], 1):
                # [1차 설명]: 순위, 카테고리 이름, 금액을 줄 맞춰 출력합니다.
                # [2차 설명]: {cat_amt:>10,}로 금액에 쉼표를 찍고 10칸 오른쪽 정렬하여 랭킹 표를 완성합니다.
                print(f"  {rank}. {cat_name:<10}: {cat_amt:>10,}원")

        # [1차 설명]: 설정된 목표 예산 객체를 변수에 꺼내옵니다.
        # [2차 설명]: summary['budget']에 저장된 그 달의 목표 예산 카드를 budget_info에 담습니다.
        budget_info = summary["budget"]
        # [1차 설명]: 구분선을 출력합니다.
        # [2차 설명]: 예산 대비 지출 평가 섹션으로 넘어가는 가로 구분선을 그립니다.
        print(f"----------------------------------------")
        # [1차 설명]: 그 달에 설정된 예산 목표 카드가 존재하는지 확인합니다.
        # [2차 설명]: if budget_info는 손님이 'budget set'으로 목표를 정해둔 달인지 검사합니다.
        if budget_info:
            # [1차 설명]: 예산 목표 금액을 변수에 담습니다.
            # [2차 설명]: budget_info.amount에서 목표 금액 숫자(예: 500000)를 꺼내 b_amount에 담습니다.
            b_amount = budget_info.amount
            # [1차 설명]: 예산 대비 지출 사용률을 백분율(%)로 계산합니다.
            # [2차 설명]: (실제 쓴 돈 / 목표 예산) * 100 연산으로 퍼센트를 구합니다.
            usage_rate = (summary["expense"] / b_amount) * 100
            # [1차 설명]: 설정된 목표 예산 금액을 출력합니다.
            # [2차 설명]: b_amount 금액을 천 단위 쉼표와 함께 출력합니다.
            print(f"• 설정 예산 : {b_amount:>12,}원")
            # [1차 설명]: 예산 사용률을 소수점 1자리까지 출력합니다.
            # [2차 설명]: usage_rate를 소수점 한 자리(.1f) 형태의 퍼센트(%)로 화면에 찍습니다.
            print(f"• 예산 사용률: {usage_rate:>11.1f}%")

            # [1차 설명]: 실제로 쓴 돈이 목표 예산을 초과했는지 비교합니다.
            # [2차 설명]: 과소비 사이렌을 울릴 조건문입니다.
            if summary["expense"] > b_amount:
                # [1차 설명]: 예산을 얼마 초과했는지 초과액을 뺄셈 계산합니다.
                # [2차 설명]: 쓴 돈(expense)에서 목표치(b_amount)를 빼서 넘친 금액을 구합니다.
                over_amount = summary["expense"] - b_amount
                # [1차 설명]: 빨간 경고 사이렌 문구를 콘솔에 출력합니다.
                # [2차 설명]: 손님에게 이번 달 예산을 넘겨 과소비했음을 경고 기호(※)와 함께 알려줍니다.
                print(f"\n※ [경고] 설정한 월 예산을 초과했습니다! (초과액: {over_amount:,}원)")
            # [1차 설명]: 예산 안에서 알뜰하게 돈을 쓴 경우입니다.
            # [2차 설명]: else는 쓴 돈이 목표 예산 이하일 때 실행됩니다.
            else:
                # [1차 설명]: 남은 예산 잔여액을 뺄셈 계산합니다.
                # [2차 설명]: 목표치(b_amount)에서 쓴 돈(expense)을 빼서 앞으로 더 쓸 수 있는 잔여 한도를 구합니다.
                remaining_budget = b_amount - summary["expense"]
                # [1차 설명]: 남은 예산 금액을 출력합니다.
                # [2차 설명]: 남은 예산 금액을 쉼표 찍어 안심할 수 있도록 출력합니다.
                print(f"• 남은 예산 : {remaining_budget:>12,}원")
        # [1차 설명]: 예산을 미리 설정해두지 않은 달인 경우입니다.
        # [2차 설명]: else는 손님이 그 달 예산을 안 정해두었을 때 실행됩니다.
        else:
            # [1차 설명]: 예산이 설정되지 않았다고 안내합니다.
            # [2차 설명]: 'budget set' 명령어로 목표치를 등록하면 사용률을 볼 수 있다고 친절히 안내합니다.
            print("• 설정된 월 예산이 없습니다. ('budget set' 명령어로 설정 가능)")
        # [1차 설명]: 요약 리포트 최종 마감선을 출력합니다.
        # [2차 설명]: 리포트의 끝을 알리는 굵은 마감선을 출력하고 줄을 바꿉니다.
        print(f"========================================\n")

    # [1차 설명]: 손님이 고른 명령어가 'export'(CSV 내보내기)인 경우입니다.
    # [2차 설명]: 가계부 거래들을 엑셀 파일로 인쇄해 주는 9번째 분기입니다.
    elif args.command == "export":
        # [1차 설명]: 회계사에게 저장 경로와 기간 조건을 넘겨 CSV 파일 작성을 요청하고 성공 건수를 받습니다.
        # [2차 설명]: count는 엑셀 파일에 몇 장의 영수증이 기록되었는지 세어주는 숫자 변수입니다.
        count = service.export_transactions_csv(
            out_path=args.out,
            month=args.month,
            from_date=args.from_date,
            to_date=args.to_date
        )
        # [1차 설명]: 내보내기 완료 메시지와 건수, 저장 파일 경로를 화면에 출력합니다.
        # [2차 설명]: "{count}건의 거래가 저장되었습니다"라고 손님 모니터에 결과를 안내합니다.
        print(f"✔ 내보내기 성공: 총 {count}건의 거래 내역이 '{args.out}' 파일로 저장되었습니다.")

    # [1차 설명]: 손님이 고른 명령어가 'import'(CSV 가져오기)인 경우입니다.
    # [2차 설명]: 외부 엑셀 파일을 읽어 가계부로 일괄 흡수하는 10번째 분기입니다.
    elif args.command == "import":
        # [1차 설명]: 회계사에게 외부 CSV 파일 경로를 넘겨 일괄 등록을 요청하고 반영된 건수를 받습니다.
        # [2차 설명]: import_transactions_csv 함수가 엑셀의 각 행을 읽어 장부에 추가하고 성공한 건수를 돌려줍니다.
        count = service.import_transactions_csv(file_path=args.input_file)
        # [1차 설명]: 가져오기 완료 메시지와 실제 반영 건수를 화면에 출력합니다.
        # [2차 설명]: "총 {count}건이 성공적으로 반영되었습니다"라고 완료 안내를 출력합니다.
        print(f"✔ 가져오기 성공: 총 {count}건의 거래 내역이 성공적으로 반영되었습니다.")