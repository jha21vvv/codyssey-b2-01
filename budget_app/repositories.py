"""
=============================================================================
[repositories.py] 데이터 흐름, 함수 순서도 및 쉬운 업무 해설
=============================================================================

1. 데이터가 들어오고 나갈 때의 함수 순서도:
   [데이터를 파일에 저장할 때: append_transaction()]
   영수증 객체 도착 ──▶ to_dict()로 납작하게 폄 ──▶ json.dumps()로 글자로 변환 ──▶ 파일 맨 끝에 볼펜으로 적기!

   [데이터를 안전하게 고치거나 지울 때: overwrite_transactions()]
   1단계: 임시 연습장 파일(tempfile)을 하나 만듦
   2단계: 수정된 새 영수증 목록을 연습장에 처음부터 끝까지 깨끗하게 적음
   3단계: os.fsync() 로 하드디스크에 잉크가 완전히 마를 때까지 꾹 눌러서 물리적 저장 강제
   4단계: os.replace() 로 0.001초 만에 연습장을 원본 장부 파일과 순식간에 맞바꿔치기!

   [데이터를 한 줄씩 꺼내볼 때: stream_transactions()]
   장부 파일 열기 ──▶ 한 줄 읽기 ──▶ 영수증 객체로 부활 ──▶ yield로 회계사에게 1장 배달 ──▶ 다음 줄 읽기 (반복)

2. 이 파일의 진짜 업무 (전문용어 0% 쉬운 설명):
   [1차 설명: 코드가 실제로 하는 일]
   - 가계부 데이터를 하드디스크의 텍스트 파일(.jsonl)에 안전하게 적어두고, 
     필요할 때 메모리가 터지지 않게 한 줄씩 꺼내주며, 
     파일을 고칠 때는 컴퓨터가 꺼져도 파일이 손상되지 않도록 안전하게 교체해 줍니다.

   [2차 업무/비유 설명: 실제 실생활 업무 관점]
   - 지하 깊은 곳에 있는 서류 보관소의 [베테랑 창고지기]입니다.
   - 컴퓨터의 메모리(RAM)는 칠판과 같아서 퇴근할 때 컴퓨터를 끄면 글씨가 싹 지워집니다.
   - 그래서 내 피 같은 돈 거래 내역을 평생 남기려면 하드디스크의 '진짜 장부 파일'에 펜으로 적어둬야 합니다.
   - 창고지기는 두 가지 특별한 기술을 씁니다:
     ① [회전초밥 배달(스트리밍 yield)]: 10만 장짜리 거대한 장부를 한꺼번에 안고 오다 허리가 부러지지 않게,
        필요한 만큼 한 장씩 쏙쏙 꺼내어 회계사에게 건네줍니다.
     ② [바꿔치기 마술(원자적 쓰기)]: 장부를 수정하다가 갑자기 정전이 되어 원본 장부가 찢어지지 않도록,
        연습장에 먼저 완벽히 적어둔 뒤 0.001초 만에 진짜 장부와 싹 맞바꿉니다.
=============================================================================
"""

# [1차 설명]: 영수증 데이터를 텍스트 글자로 바꾸거나 다시 읽기 위한 도구입니다.
# [2차 업무 설명]: 장부에 한글과 숫자를 가지런히 적어 넣고 읽기 위한 만년필입니다.
import json
# [1차 설명]: 폴더를 만들고, 파일 경로를 합치고, 파일 이름을 순간 교체하기 위해 가져옵니다.
# [2차 업무 설명]: 서류 보관소 서랍을 정리하고 파일 이름을 바꿔주는 사무용 도구입니다.
import os
# [1차 설명]: 안전한 바꿔치기 마술을 하기 위해 비밀 연습장(임시 파일)을 만들어주는 도구입니다.
# [2차 업무 설명]: 원본 장부가 다치지 않게 임시로 쓸 수 있는 연습장 공책을 한 권 꺼내는 일입니다.
import tempfile
# [1차 설명]: 한 번에 한 장씩 꺼내주는 배달원(Generator) 타입을 표시하기 위해 가져옵니다.
# [2차 업무 설명]: 영수증을 한 장씩 전달해 주는 회전초밥 접시 모양의 타입 힌트입니다.
from typing import Generator, List, Optional

# [1차 설명]: models.py에서 정의한 영수증 양식 서식들을 가져옵니다.
# [2차 업무 설명]: 가계부 공식 규격 용지(예산 카드, 카테고리 명찰, 거래 영수증)를 손에 쥐는 일입니다.
from .models import Budget, Category, Transaction


# [1차 설명]: 파일 입출력을 도맡아 처리하는 저장소 클래스입니다.
# [2차 업무 설명]: 지하 서류 보관소의 든든한 [창고지기]입니다.
class FileRepository:
    # [1차 설명]: 창고지기 객체가 생성될 때 장부를 보관할 폴더 위치를 배정받습니다.
    # [2차 업무 설명]: "당신이 일할 보관소 서랍은 ./data 폴더입니다"라고 일터를 정해주는 일입니다.
    def __init__(self, data_dir: str = "./data") -> None:
        # [1차 설명]: 보관 폴더 경로를 기억해 둡니다.
        self.data_dir = data_dir
        # [1차 설명]: 폴더가 없으면 새로 만들고 이미 있으면 통과합니다.
        # [2차 업무 설명]: 서류를 꽂아둘 캐비닛 방이 없으면 방부터 깨끗하게 만드는 일입니다.
        os.makedirs(self.data_dir, exist_ok=True)

        # [1차 설명]: 3가지 핵심 장부 파일의 전체 경로를 지정합니다.
        # [2차 업무 설명]: 거래 내역 장부, 카테고리 장부, 예산 장부의 서랍 칸 위치를 딱 정해두는 일입니다.
        self.tx_file = os.path.join(self.data_dir, "transactions.jsonl")
        self.cat_file = os.path.join(self.data_dir, "categories.jsonl")
        self.budget_file = os.path.join(self.data_dir, "budgets.jsonl")

        # [1차 설명]: 장부 파일들이 진짜 있는지 확인하고 초기화하는 함수를 실행합니다.
        # [2차 업무 설명]: 출근하자마자 서랍을 열어서 장부들이 잘 꽂혀있는지 점검하는 일입니다.
        self._initialize_storage()

    # [1차 설명]: 빈 장부 파일을 준비하고 기본 카테고리를 채워 넣는 초기화 함수입니다.
    # [2차 업무 설명]: 새 가계부를 처음 쓰는 손님을 위해 빈 공책을 꺼내두고 기본 분류(식비, 교통 등)를 미리 적어두는 일입니다.
    def _initialize_storage(self) -> None:
        # [1차 설명]: 거래 장부와 예산 장부가 없으면 깨끗한 빈 파일을 만듭니다.
        for path in (self.tx_file, self.budget_file):
            if not os.path.exists(path):
                open(path, "a", encoding="utf-8").close()

        # [1차 설명]: 카테고리 장부가 비어있다면 기본 카테고리 6개를 채웁니다.
        # [2차 업무 설명]: 처음 온 손님이 바로 가계부를 쓸 수 있게 "식비", "교통", "주거", "쇼핑", "급여", "기타"를 미리 적어둡니다.
        if not os.path.exists(self.cat_file) or os.path.getsize(self.cat_file) == 0:
            default_categories = ["식비", "교통", "주거", "쇼핑", "급여", "기타"]
            self.save_categories(default_categories)

    # -------------------------------------------------------------------------
    # 1. Transactions (거래 내역) 스트리밍 및 쓰기
    # -------------------------------------------------------------------------

    # [1차 설명]: 장부 파일에서 영수증을 한 장씩 꺼내서 호출자에게 전달해 주는 함수입니다.
    # [2차 업무 설명]: 회전초밥 레일처럼, 10만 장짜리 거대한 장부에서 영수증을 딱 한 장씩만 꺼내서 회계사 손에 쥐여주는 일입니다.
    def stream_transactions(self) -> Generator[Transaction, None, None]:
        # [1차 설명]: 거래 장부 파일이 존재하는지 검사합니다.
        # [2차 업무 설명]: 서랍에 transactions.jsonl 장부가 없으면 아무것도 줄 수 없으니 즉시 종료합니다.
        if not os.path.exists(self.tx_file):
            # [1차 설명]: 장부가 없으므로 함수를 마칩니다.
            # [2차 업무 설명]: 빈손으로 작업을 끝냅니다.
            return

        # [1차 설명]: 장부 파일을 읽기 모드(r)로 열어 파일 관리자를 준비합니다.
        # [2차 업무 설명]: transactions.jsonl 장부 책을 펼쳐서 읽을 준비를 합니다.
        with open(self.tx_file, "r", encoding="utf-8") as f:
            # [1차 설명]: 파일에서 한 줄씩 순서대로 읽습니다.
            # [2차 업무 설명]: 장부 책장을 한 줄씩 아래로 내려가며 훑어봅니다.
            for line in f:
                # [1차 설명]: 줄 앞뒤의 불필요한 줄바꿈과 공백을 잘라냅니다.
                # [2차 업무 설명]: 엔터 줄바꿈 빈칸을 지워 깨끗한 글자만 남깁니다.
                line_str = line.strip()
                # [1차 설명]: 빈 줄인지 검사합니다.
                # [2차 업무 설명]: 아무 내용도 없는 빈 줄이면 영수증이 아니므로 건너뜁니다.
                if not line_str:
                    # [1차 설명]: 다음 줄로 넘어갑니다.
                    # [2차 업무 설명]: 아래 코드를 건너뛰고 다음 줄을 읽습니다.
                    continue
                # [1차 설명]: 파일에 적힌 한 줄 글자를 딕셔너리로 바꿉니다.
                # [2차 업무 설명]: json 글자를 파이썬이 다루기 쉬운 서류 묶음(dict)으로 해독합니다.
                data = json.loads(line_str)
                # [1차 설명]: 정식 Transaction 영수증으로 조립해서 밖으로 1장 배달합니다.
                # [2차 업무 설명]: yield는 회전초밥 접시에 영수증 1장을 얹어서 회계사 손에 건네주는 배달 명령입니다.
                yield Transaction.from_dict(data)

    # [1차 설명]: 새로운 거래 영수증 1건을 파일 맨 끝에 덧붙여 씁니다.
    # [2차 업무 설명]: 오늘 새로 들어온 영수증 1장을 장부 맨 뒷장에 볼펜으로 예쁘게 한 줄 추가하는 일입니다.
    def append_transaction(self, tx: Transaction) -> None:
        # [1차 설명]: 추가 모드(a)로 장부 파일을 엽니다.
        # [2차 업무 설명]: 기존 내용을 지우지 않고 맨 뒤에 덧붙여 쓰기 위해 'a' 모드로 책을 펼칩니다.
        with open(self.tx_file, "a", encoding="utf-8") as f:
            # [1차 설명]: 영수증 객체를 한 줄짜리 JSON 문자열로 변환합니다.
            # [2차 업무 설명]: 영수증 종이를 파일에 적기 좋은 텍스트 글자로 인쇄합니다.
            json_line = json.dumps(tx.to_dict(), ensure_ascii=False)
            # [1차 설명]: 글자 뒤에 줄바꿈(\n)을 붙여 파일에 씁니다.
            # [2차 업무 설명]: 장부 맨 뒷줄에 볼펜으로 글자를 적고 다음 줄을 위해 줄을 바꿉니다.
            f.write(json_line + "\n")

    # [1차 설명]: 기존 거래 목록 전체를 안전한 임시 파일 방식으로 덮어씁니다.
    # [2차 업무 설명]: 컴퓨터가 갑자기 꺼져도 장부가 찢어지지 않도록, 연습장에 먼저 완벽히 베껴 쓴 다음 0.001초 만에 원본 장부와 싹 맞바꿔치기하는 일입니다.
    def overwrite_transactions(self, transactions: List[Transaction]) -> None:
        # [1차 설명]: 원본 장부가 있는 폴더 경로를 알아냅니다.
        # [2차 업무 설명]: 바꿔치기할 연습장을 원본 장부와 같은 서랍(폴더) 안에 만들어야 순간 교체가 가능하기 때문입니다.
        dir_name = os.path.dirname(self.tx_file)
        # [1차 설명]: 임시 파일(연습장)을 만듭니다.
        # [2차 업무 설명]: 겉표지가 없는 깨끗한 새 연습장을 서랍 안에 한 권 꺼냅니다.
        with tempfile.NamedTemporaryFile("w", dir=dir_name, delete=False, encoding="utf-8") as tf:
            # [1차 설명]: 임시 파일의 전체 경로 이름을 변수에 보관합니다.
            # [2차 업무 설명]: 연습장의 파일 위치를 temp_path에 적어둡니다.
            temp_path = tf.name
            # [1차 설명]: 영수증 목록에서 영수증을 1장씩 꺼냅니다.
            # [2차 업무 설명]: 장부에 남길 영수증들을 하나씩 차례로 꺼냅니다.
            for tx in transactions:
                # [1차 설명]: 영수증을 JSON 텍스트 한 줄로 만듭니다.
                # [2차 업무 설명]: 영수증을 글자로 바꿉니다.
                #마이: 데려올떄 리스트로 했으니 이걸 다시 하나씩 딕셔너리로 함. dumps은 문자열로 만든 단계. 저장까진 안한단계
                line = json.dumps(tx.to_dict(), ensure_ascii=False)
                # [1차 설명]: 연습장에 한 줄 적고 줄바꿈을 합니다.
                # [2차 업무 설명]: 연습장에 볼펜으로 글씨를 적습니다.
                #마이: 데이터들을 하나의 데이터로 만들기위해 모음.
                tf.write(line + "\n")
            # [1차 설명]: 컴퓨터 메모리에 머물러 있는 글자를 디스크 버퍼로 밀어냅니다.
            # [2차 업무 설명]: 펜 끝에 묻은 잉크를 종이에 꾹 찍어냅니다.
            #마이: 파이썬이 관리하던 메모리 버퍼를 OS가 관리하는 파일 버퍼로 옮김. 지워지지 말라고 하는 조치
            tf.flush()
            # [1차 설명]: 하드디스크에 물리적으로 완전히 기록되도록 강제합니다.
            # [2차 업무 설명]: 종이에 잉크가 번지지 않도록 도장을 꾹 눌러서 완전히 말려 굳히는 일입니다.
            #마이: 그 파일에 대한 모든 버퍼를 디스크에 강제로 반영해라
            os.fsync(tf.fileno())

        # [1차 설명]: 임시 파일을 원본 파일로 순간 교체합니다.
        # [2차 업무 설명]: 연습장을 원본 장부 자리에 순식간에 쏙 집어넣어 교체를 끝냅니다.
        # 마이: 원본파일을 지우고 임시파일을 원본파일로 바꿔치기. os.replace는 원자적 교체라서 중간에 끊기지 않음.파일 이름/경로 자체를 “바꾸는” 건 아니고,“원본 파일 위치에 새 파일을 덮어놓는” 동작입니다.
        os.replace(temp_path, self.tx_file)

    # -------------------------------------------------------------------------
    # 2. Categories (카테고리 목록) 관리
    # -------------------------------------------------------------------------

    # [1차 설명]: 카테고리 이름을 한 줄씩 꺼내줍니다.
    # [2차 업무 설명]: 카테고리 장부에서 분류 이름표("식비", "교통")를 1개씩 꺼내주는 배달 창구입니다.
    def stream_categories(self) -> Generator[str, None, None]:
        # [1차 설명]: 카테고리 파일이 존재하는지 검사합니다.
        # [2차 업무 설명]: categories.jsonl 파일이 없으면 즉시 종료합니다.
        if not os.path.exists(self.cat_file):
            # [1차 설명]: 함수를 마칩니다.
            # [2차 업무 설명]: 작업 종료입니다.
            return

        # [1차 설명]: 카테고리 파일을 읽기 모드로 엽니다.
        # [2차 업무 설명]: categories.jsonl 서랍을 엽니다.
        with open(self.cat_file, "r", encoding="utf-8") as f:
            # [1차 설명]: 파일의 각 줄을 순회합니다.
            # [2차 업무 설명]: 한 줄씩 읽어 내려갑니다.
            for line in f:
                # [1차 설명]: 공백을 제거합니다.
                # [2차 업무 설명]: 빈칸을 정리합니다.
                line_str = line.strip()
                # [1차 설명]: 빈 줄인지 검사합니다.
                # [2차 업무 설명]: 빈 줄이면 넘어갑니다.
                if not line_str:
                    # [1차 설명]: 다음 줄로 넘어갑니다.
                    # [2차 업무 설명]: 스킵합니다.
                    continue
                # [1차 설명]: JSON 글자를 파이썬 딕셔너리로 해독합니다.
                # [2차 업무 설명]: {"name": "식비"} 글자를 파이썬 객체로 바꿉니다.
                data = json.loads(line_str)
                # [1차 설명]: name 문자열을 바깥으로 하나씩 배달합니다.
                # [2차 업무 설명]: "식비" 단어를 호출자에게 건네줍니다.
                yield data["name"]

    # [1차 설명]: 카테고리 전체 목록을 리스트로 반환합니다.
    # [2차 업무 설명]: 배달받은 카테고리 단어들을 바구니(List)에 몽땅 담아서 돌려주는 일입니다.
    def load_categories(self) -> List[str]:
        # [1차 설명]: stream_categories 배달원에게서 모든 단어를 받아 리스트로 묶어 반환합니다.
        # [2차 업무 설명]: ['식비', '교통', '주거'] 목록 상자를 반환합니다.
        return list(self.stream_categories())

    # [1차 설명]: 중복을 없애고 카테고리 목록을 안전하게 파일에 저장합니다.
    # [2차 업무 설명]: 겹치는 이름을 지우고, 연습장에 적은 뒤 원본 파일과 맞바꿔치기하여 안전하게 저장하는 일입니다.
    def save_categories(self, categories: List[str]) -> None:
        # [1차 설명]: 순서를 유지하면서 중복된 카테고리 이름을 제거합니다.
        # [2차 업무 설명]: "식비"가 두 번 적혀있으면 하나를 지워 깔끔한 명단을 만듭니다.
        # 마이: unique_cats = list(dict.fromkeys(categories)) 딕셔너리의 키값으로 만들어서 중복이 안되게 조치후에 다시 리스트로 만드는 방식..
        unique_cats = list(dict.fromkeys(categories))
        # [1차 설명]: 파일이 위치한 폴더 이름을 가져옵니다.
        # [2차 업무 설명]: 임시 파일을 만들 같은 방 위치를 확인합니다.
        dir_name = os.path.dirname(self.cat_file)

        # [1차 설명]: 임시 연습장 파일을 만듭니다.
        # [2차 업무 설명]: 원본 손상을 막기 위해 임시 공책을 엽니다.
        with tempfile.NamedTemporaryFile("w", dir=dir_name, delete=False, encoding="utf-8") as tf:
            # [1차 설명]: 임시 파일 경로를 저장합니다.
            # [2차 업무 설명]: 연습장 이름을 기억해 둡니다.
            temp_path = tf.name
            # [1차 설명]: 중복이 제거된 카테고리들을 하나씩 순회합니다.
            # [2차 업무 설명]: 카테고리 단어를 하나씩 꺼냅니다.
            for cat in unique_cats:
                # [1차 설명]: {"name": cat} 형태의 JSON 텍스트로 만듭니다.
                # [2차 업무 설명]: 카테고리를 텍스트 한 줄로 포장합니다.
                line = json.dumps({"name": cat}, ensure_ascii=False)
                # [1차 설명]: 연습장에 한 줄 적습니다.
                # [2차 업무 설명]: 볼펜으로 기록합니다.
                tf.write(line + "\n")
            # [1차 설명]: 메모리 버퍼를 비웁니다.
            # [2차 업무 설명]: 잉크를 털어냅니다.
            tf.flush()
            # [1차 설명]: 디스크에 물리적 기록을 강제합니다.
            # [2차 업무 설명]: 도장을 꾹 눌러 완전히 굳힙니다.
            os.fsync(tf.fileno())

        # [1차 설명]: 임시 파일을 원본 카테고리 파일로 교체합니다.
        # [2차 업무 설명]: 0.001초 만에 장부를 싹 바꿔치기합니다.
        #마이: 파이썬이 관리하던 메모리 버퍼를 OS가 관리하는 파일 버퍼로 옮김. 지워지지 말라고 하는 조치
        #마이: 그 파일에 대한 모든 버퍼를 디스크에 강제로 반영해라
        # 마이: 원본파일을 지우고 임시파일을 원본파일로 바꿔치기. os.replace는 원자적 교체라서 중간에 끊기지 않음.파일 이름/경로 자체를 “바꾸는” 건 아니고,“원본 파일 위치에 새 파일을 덮어놓는” 동작입니다.

        os.replace(temp_path, self.cat_file)

    # -------------------------------------------------------------------------
    # 3. Budgets (월별 예산) 관리
    # -------------------------------------------------------------------------

    # [1차 설명]: 저장된 예산 목록을 한 줄씩 꺼내줍니다.
    # [2차 업무 설명]: budgets.jsonl 장부에서 예산 목표 카드를 1장씩 꺼내주는 배달 창구입니다.
    def stream_budgets(self) -> Generator[Budget, None, None]:
        # [1차 설명]: 예산 파일이 존재하는지 검사합니다.
        # [2차 업무 설명]: 장부 파일이 없으면 즉시 작업을 끝냅니다.
        if not os.path.exists(self.budget_file):
            # [1차 설명]: 함수를 마칩니다.
            # [2차 업무 설명]: 종료합니다.
            return

        # [1차 설명]: 예산 파일을 읽기 모드로 엽니다.
        # [2차 업무 설명]: budgets.jsonl 책을 펼칩니다.
        with open(self.budget_file, "r", encoding="utf-8") as f:
            # [1차 설명]: 한 줄씩 읽어 내려갑니다.
            # [2차 업무 설명]: 예산 기록을 순서대로 읽습니다.
            for line in f:
                # [1차 설명]: 줄 앞뒤 공백을 제거합니다.
                # [2차 업무 설명]: 빈칸을 정리합니다.
                line_str = line.strip()
                # [1차 설명]: 빈 줄인지 확인합니다.
                # [2차 업무 설명]: 빈 줄이면 건너뜁니다.
                if not line_str:
                    # [1차 설명]: 다음 줄로 이동합니다.
                    # [2차 업무 설명]: 스킵합니다.
                    continue
                # [1차 설명]: JSON 글자를 파이썬 딕셔너리로 해독합니다.
                # [2차 업무 설명]: 글자를 파이썬 서류로 해독합니다.
                data = json.loads(line_str)
                # [1차 설명]: 정식 Budget 객체로 조립하여 바깥으로 배달합니다.
                # [2차 업무 설명]: 공식 예산 목표 카드를 1장 건네줍니다.
                yield Budget.from_dict(data)

    # [1차 설명]: 특정 월의 예산 카드를 찾아옵니다.
    # [2차 업무 설명]: "2026년 5월에 목표로 정해둔 예산 카드가 있나?" 서랍에서 찾아오는 일입니다.
    def get_budget(self, month: str) -> Optional[Budget]:
        # [1차 설명]: 저장된 모든 예산 카드를 하나씩 확인합니다.
        # [2차 업무 설명]: 장부의 예산 카드들을 하나씩 살펴봅니다.
        for b in self.stream_budgets():
            # [1차 설명]: 찾는 대상 월과 일치하는 카드인지 확인합니다.
            # [2차 업무 설명]: 손님이 찾는 바로 그 달의 카드인지 대조합니다.
            if b.month == month:
                # [1차 설명]: 찾은 예산 카드를 반환합니다.
                # [2차 업무 설명]: 목표 예산 카드를 건네줍니다.
                return b
        # [1차 설명]: 끝까지 찾아도 없으면 None을 돌려줍니다.
        # [2차 업무 설명]: 그 달에 설정된 예산이 없다고 빈손으로 돌아옵니다.
        return None

    # [1차 설명]: 특정 월의 예산을 등록하거나 변경하여 안전하게 저장합니다.
    # [2차 업무 설명]: "5월 목표 예산 50만 원" 카드를 새롭게 장부에 기록하는 일입니다.
    def set_budget(self, budget: Budget) -> None:
        # [1차 설명]: 기존 예산 카드들을 {월: 금액} 딕셔너리 지도로 모읍니다.
        # [2차 업무 설명]: 기존에 설정된 달별 예산들을 한눈에 볼 수 있게 지도 형태로 정리합니다.
        budgets_map = {b.month: b.amount for b in self.stream_budgets()}
        # [1차 설명]: 새로운 월의 예산 금액을 딕셔너리에 추가하거나 덮어씁니다.
        # [2차 업무 설명]: 이번에 새로 들어온 목표 금액으로 지도 내용을 갱신합니다.
        budgets_map[budget.month] = budget.amount

        # [1차 설명]: 예산 파일이 있는 폴더 경로를 확인합니다.
        # [2차 업무 설명]: 임시 파일을 만들 디렉터리를 확인합니다.
        dir_name = os.path.dirname(self.budget_file)
        # [1차 설명]: 안전한 임시 연습장 파일을 만듭니다.
        # [2차 업무 설명]: 원본 보존을 위해 연습장 공책을 준비합니다.
        with tempfile.NamedTemporaryFile("w", dir=dir_name, delete=False, encoding="utf-8") as tf:
            # [1차 설명]: 임시 파일 경로를 변수에 담습니다.
            # [2차 업무 설명]: 연습장 이름을 기억해 둡니다.
            temp_path = tf.name
            # [1차 설명]: 월별로 오름차순 정렬하여 하나씩 꺼냅니다.
            # [2차 업무 설명]: 1월, 2월, 3월 달력 순서대로 차례로 줄을 세웁니다.
            for m, amt in sorted(budgets_map.items()):
                # [1차 설명]: {"month": m, "amount": amt}를 JSON 문자열로 변환합니다.
                # [2차 업무 설명]: 예산 데이터를 텍스트 한 줄로 만듭니다.
                line = json.dumps({"month": m, "amount": amt}, ensure_ascii=False)
                # [1차 설명]: 연습장에 한 줄 기록합니다.
                # [2차 업무 설명]: 볼펜으로 적습니다.
                tf.write(line + "\n")
            # [1차 설명]: 메모리 버퍼를 비웁니다.
            # [2차 업무 설명]: 잉크를 털어냅니다.
            tf.flush()
            # [1차 설명]: 하드디스크 물리 기록을 강제합니다.
            # [2차 업무 설명]: 도장을 꾹 눌러 굳힙니다.
            os.fsync(tf.fileno())

        # [1차 설명]: 임시 파일을 원본 예산 파일로 순간 맞바꿔치기합니다.
        # [2차 업무 설명]: 0.001초 만에 원본 장부와 교체하여 안전하게 저장을 끝냅니다.
        os.replace(temp_path, self.budget_file)