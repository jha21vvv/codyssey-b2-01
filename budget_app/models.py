"""
=============================================================================
[models.py] 데이터 흐름, 함수 순서도 및 쉬운 업무 해설
=============================================================================

1. 데이터가 들어오고 나갈 때의 함수 순서도:
   사용자가 입력한 거래 정보 (날짜, 수입/지출, 카테고리, 금액 등) 도착
       │
       ▼ [1단계] Transaction 클래스 호출
       │         영수증 빈 용지에 날짜, 금액, 카테고리 등의 글자를 채워 넣음
       │
       ▼ [2단계] __post_init__() 함수 자동 실행 (영수증 자체 검사관 출동!)
       │         ├─ 1. 수입(income) 또는 지출(expense) 단어가 맞는지 검사 ──(아니면 거절!)
       │         ├─ 2. 달력에 진짜 있는 날짜(YYYY-MM-DD)인지 검사 ──────────(아니면 거절!)
       │         ├─ 3. 금액이 1원 이상 양수인지 검사 ─────────────────────(아니면 거절!)
       │         └─ 4. 카테고리 칸이 비어있지 않은지 검사 ─────────────────(아니면 거절!)
       │
       ▼ [3단계] 검사 모두 통과!
       │         안전하고 올바른 영수증 객체가 완성되어 메모리에 등록됨
       │
       ▼ [4단계] to_dict() 호출 (파일에 저장할 때)
       │         장부 파일에 적기 좋게 영수증을 납작한 데이터 묶음으로 폄
       │
       ▼ [5단계] from_dict() 호출 (파일에서 읽어올 때)
                 장부에 적힌 글자를 읽어서 다시 엄격한 영수증 객체로 재조립함

2. 이 파일의 진짜 업무 (전문용어 0% 쉬운 설명):
   [1차 설명: 코드가 실제로 하는 일]
   - 거래 내역(Transaction), 월별 예산(Budget), 카테고리(Category)가 가져야 할 
     정보의 모양을 정해두고, 엉터리 데이터가 들어오면 즉시 거절하여 프로그램을 보호합니다.

   [2차 업무/비유 설명: 실제 실생활 업무 관점]
   - 은행의 [공식 입출금 전표(영수증 서식)]입니다.
   - 아무 이면지에 낙서하듯 적은 돈 거래는 장부에 올릴 수 없습니다.
   - 반드시 공식 전표에 적어야 하고, 전표를 내자마자 은행원이 
     "손님, 달력에 2월 30일은 없는 날인데요?", "손님, 금액에 마이너스 5만 원을 쓰시면 안 됩니다!" 하고 
     돋보기를 들고 엉터리 데이터를 돌려보내는 것과 똑같습니다.
=============================================================================
"""

# [1차 설명]: 데이터 클래스를 간편하게 만들어주는 파이썬 기본 도구들을 가져옵니다.
# [2차 업무 설명]: 영수증 양식 서식을 자동으로 예쁘게 인쇄해 주는 서식 인쇄기를 가져오는 일입니다.
from dataclasses import dataclass, field
# [1차 설명]: 날짜 형식이 진짜 달력에 존재하는지 검사하기 위해 날짜 도구를 가져옵니다.
# [2차 업무 설명]: 2월 30일 같은 가짜 날짜를 잡아내기 위해 공식 달력 책을 펼쳐두는 일입니다.
from datetime import datetime
# [1차 설명]: 코드에 변수 종류(글자, 숫자 등)를 표시해 주는 타입 도구들을 가져옵니다.
# [2차 업무 설명]: 영수증 빈칸마다 "여기는 글자 쓰는 칸", "여기는 숫자 쓰는 칸"이라고 이름표를 붙여두는 일입니다.
from typing import Any, Dict, List, Literal


# [1차 설명]: 거래 내역 1건을 보관하는 영수증 클래스입니다.
# [2차 업무 설명]: 돈을 벌거나 쓸 때마다 작성하는 '가계부 공식 영수증 종이'입니다.
# 마이: @dataclass는 클래스에 자동으로 __init__, __repr__, __eq__ 등의 메서드를 생성해주는 데코레이터입니다. 즉, Transaction 클래스의 인스턴스를 생성할 때 필요한 초기화 메서드와 객체를 문자열로 
# 표현하는 메서드 등을 자동으로 만들어줍니다.
@dataclass
class Transaction:
    # [1차 설명]: 거래마다 부여되는 고유 식별 번호 문자열입니다.
    # [2차 업무 설명]: 영수증이 섞이지 않도록 맨 위에 찍어주는 [영수증 일련번호(주민번호)] 칸입니다 (예: "a1b2c3d4").
    id: str

    # [1차 설명]: "income"(수입) 또는 "expense"(지출)만 허용하는 문자열 칸입니다.
    # [2차 업무 설명]: 오늘 거래가 내 지갑으로 들어온 돈(수입)인지, 밖으로 나간 돈(지출)인지 동그라미 치는 칸입니다.
    type: Literal["income", "expense"]

    # [1차 설명]: 거래가 발생한 날짜 문자열입니다.
    # [2차 업무 설명]: 돈을 언제 썼는지 "2026-05-15" 처럼 년-월-일로 날짜 도장을 찍는 칸입니다.
    date: str

    # [1차 설명]: 거래 금액을 나타내는 양의 정수 숫자입니다.
    # [2차 업무 설명]: 지갑에서 실제로 얼마를 꺼내 썼는지 "12000" 처럼 원 단위 돈 액수를 적는 칸입니다.
    amount: int

    # [1차 설명]: 거래 항목을 분류하는 카테고리 이름 문자열입니다.
    # [2차 업무 설명]: 밥 먹는 데 썼으면 "식비", 버스 탔으면 "교통"이라고 어디에 쓴 돈인지 적는 칸입니다.
    category: str

    # [1차 설명]: 거래에 대한 추가 설명 메모입니다 (안 적으면 빈 글자).
    # [2차 업무 설명]: "점심 김치찌개 친구랑 더치페이" 처럼 나중에 기억하기 위해 덧붙여 적는 메모 칸입니다.
    memo: str = ""

    # [1차 설명]: 여러 개의 태그 단어를 담는 리스트입니다 (기본값은 빈 리스트).
    # [2차 업무 설명]: ["외식", "점심"] 처럼 나중에 한꺼번에 검색하기 편하게 영수증에 꼬리표를 달아두는 칸입니다.
    tags: list[str] = field(default_factory=list)

    # [1차 설명]: 영수증이 만들어지자마자 내용물이 진짜 올바른지 검사하는 함수입니다.
    # [2차 업무 설명]: 영수증을 창구에 내자마자 은행원이 돋보기를 들고 "가짜 날짜나 마이너스 금액이 없는지" 확인하는 일입니다.
    def __post_init__(self) -> None:
        # [1차 설명]: 거래 구분이 수입이나 지출 둘 중 하나가 맞는지 확인합니다.
        # [2차 업무 설명]: 수입/지출 칸에 엉뚱한 외계어가 적혀 있으면 즉시 퇴짜를 놓습니다.
        if self.type not in ("income", "expense"):
            raise ValueError(f"유효하지 않은 거래 타입입니다: '{self.type}'. 'income' 또는 'expense'여야 합니다.")

        # [1차 설명]: 날짜 문자열이 진짜 달력에 존재하는 날인지 검사를 시도합니다.
        # [2차 업무 설명]: 달력 책을 넘겨보며 "2026-05-15"가 진짜 있는 날인지 대조해 봅니다.
        try:
            datetime.strptime(self.date, "%Y-%m-%d")
        # [1차 설명]: 달력에 없는 날짜(예: 2월 30일)이거나 글자 모양이 틀렸을 때 실행됩니다.
        # [2차 업무 설명]: "손님, 달력에 그런 날짜는 없습니다!" 하고 퇴짜를 놓습니다.
        except ValueError:
            raise ValueError(f"유효하지 않은 날짜 형식입니다: '{self.date}'. 'YYYY-MM-DD' 형식이어야 합니다.")

        # [1차 설명]: 금액이 숫자가 아니거나 0원 이하(마이너스)인지 확인합니다.
        # [2차 업무 설명]: 가계부에는 무조건 1원 이상의 진짜 돈 액수가 적혀야 하므로 마이너스 금액을 거절합니다.
        if not isinstance(self.amount, int) or self.amount <= 0:
            raise ValueError(f"금액은 0보다 큰 양수 정수여야 합니다: {self.amount}")

        # [1차 설명]: 카테고리 칸이 비어있거나 공백 스페이스바만 있는지 확인합니다.
        # [2차 업무 설명]: 어디에 쓴 돈인지 모르면 나중에 한 달 결산을 낼 수 없으므로 거절합니다.
        if not self.category or not self.category.strip():
            raise ValueError("카테고리는 비어 있을 수 없습니다.")

    # [1차 설명]: 영수증 객체를 키-값 딕셔너리 형태로 변환하여 반환합니다.
    # [2차 업무 설명]: 영수증 종이를 장부 서랍(파일)에 차곡차곡 넣기 편하게 납작한 서류 봉투 형태로 접는 일입니다.
    def to_dict(self) -> dict[str, Any]:
        # [1차 설명]: 영수증의 7가지 항목을 딕셔너리로 묶어 반환합니다.
        # [2차 업무 설명]: 영수증의 번호(id), 구분(type), 날짜(date), 금액(amount), 항목(category), 메모(memo), 태그(tags)를 이름표와 함께 묶어 서랍에 넣을 준비를 합니다.
        return {
            "id": self.id,
            "type": self.type,
            "date": self.date,
            "amount": self.amount,
            "category": self.category,
            "memo": self.memo,
            "tags": self.tags,
        }

    # [1차 설명]: 딕셔너리 데이터로부터 영수증 객체를 다시 복원합니다.
    # [2차 업무 설명]: 장부 서랍(파일)에서 꺼낸 서류 봉투의 내용을 읽어서 다시 온전한 정식 영수증으로 펼쳐내는 일입니다.
    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "Transaction":
        # [1차 설명]: 딕셔너리 속 각 칸의 데이터를 알맞은 타입(문자, 숫자, 리스트)으로 변환하여 Transaction 객체를 생성합니다.
        # [2차 업무 설명]: 서류에 적힌 글씨들을 확인하여 글자는 글자로, 돈 액수는 숫자(int)로, 태그는 목록(list)으로 규격에 맞게 새 영수증을 찍어냅니다.
        return cls(
            id=str(data["id"]),
            type=data["type"],
            date=str(data["date"]),
            amount=int(data["amount"]),
            category=str(data["category"]),
            memo=str(data.get("memo", "")),
            tags=list(data.get("tags", [])),
        )


# [1차 설명]: 한 달 목표 예산 금액을 보관하는 예산 클래스입니다.
# [2차 업무 설명]: "이번 달에는 지출을 최대 얼마까지만 쓰겠다"라고 적어두는 [월별 예산 목표 카드]입니다.
@dataclass
class Budget:
    # [1차 설명]: 목표 대상 연월 문자열입니다 (예: "2026-05").
    # [2차 업무 설명]: 어느 달의 예산인지 "2026년 5월"이라고 적어두는 칸입니다.
    month: str

    # [1차 설명]: 목표 예산 한도 금액 숫자입니다 (원 단위).
    # [2차 업무 설명]: "이번 달 한도 50만 원" 처럼 지출 상한선 돈을 적어두는 칸입니다.
    amount: int

    # [1차 설명]: 예산 카드가 만들어질 때 연월 형식과 양수 금액을 검사합니다.
    # [2차 업무 설명]: 예산 목표에 마이너스 돈을 적거나 엉터리 달을 적지 않았는지 점검하는 일입니다.
    def __post_init__(self) -> None:
        # [1차 설명]: "년-월" 형태의 날짜인지 달력 대조를 시도합니다.
        # [2차 업무 설명]: 손님이 적은 "2026-05"가 진짜 있는 달인지 확인해 봅니다.
        try:
            # [1차 설명]: 문자열을 "%Y-%m" 형식으로 맞춰봅니다.
            # [2차 업무 설명]: strptime은 글자를 쪼개서 달력 월과 일치하는지 맞추어보는 함수입니다.
            datetime.strptime(self.month, "%Y-%m")
        # [1차 설명]: 형식이 틀리거나 없는 달일 때 에러를 잡습니다.
        # [2차 업무 설명]: "손님, 2026-15월 같은 달은 없습니다!" 하고 에러를 던집니다.
        except ValueError:
            # [1차 설명]: 올바른 YYYY-MM 형식을 쓰라고 에러를 발생시킵니다.
            # [2차 업무 설명]: 손님에게 월 표기법이 틀렸다고 퇴짜를 놓습니다.
            raise ValueError(f"유효하지 않은 월 형식입니다: '{self.month}'. 'YYYY-MM' 형식이어야 합니다.")

        # [1차 설명]: 예산 금액이 숫자가 아니거나 0 이하인지 검사합니다.
        # [2차 업무 설명]: 한 달 예산이 0원이거나 마이너스면 가계부 목표의 의미가 없으므로 거절합니다.
        if not isinstance(self.amount, int) or self.amount <= 0:
            # [1차 설명]: 금액이 양수여야 한다는 에러를 던집니다.
            # [2차 업무 설명]: 1원 이상의 진짜 돈을 적으라고 거절 메시지를 띄웁니다.
            raise ValueError(f"예산 금액은 0보다 큰 양수 정수여야 합니다: {self.amount}")

    # [1차 설명]: 예산 정보를 딕셔너리로 바꿉니다.
    # [2차 업무 설명]: 파일에 저장하기 위해 예산 카드 내용을 납작하게 포장하는 일입니다.
    def to_dict(self) -> dict[str, Any]:
        # [1차 설명]: 대상 월과 예산 금액을 딕셔너리로 묶어 반환합니다.
        # [2차 업무 설명]: "2026-05월: 500,000원" 서류 봉투를 만듭니다.
        return {
            "month": self.month,
            "amount": self.amount,
        }

    # [1차 설명]: 딕셔너리에서 예산 객체를 다시 되살려냅니다.
    # [2차 업무 설명]: 파일에서 읽은 데이터로 정식 예산 카드를 다시 발급하는 일입니다.
    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "Budget":
        # [1차 설명]: 월 글자와 금액 숫자를 꺼내서 새 Budget 객체를 만듭니다.
        # [2차 업무 설명]: 파일에 적힌 데이터를 토대로 정식 예산 목표 카드를 발급합니다.
        return cls(
            month=str(data["month"]),
            amount=int(data["amount"]),
        )


# [1차 설명]: 카테고리 이름 하나를 다루는 보조 클래스입니다.
# [2차 업무 설명]: "식비", "교통", "쇼핑" 같은 [지출 분류 이름표] 하나를 보관하는 틀입니다.
@dataclass
class Category:
    # [1차 설명]: 카테고리의 고유 명칭 문자열입니다.
    # [2차 업무 설명]: 분류 이름표에 적힐 진짜 글자입니다 (예: "식비").
    name: str

    # [1차 설명]: 이름이 비어있지 않은지 검사하고 공백을 제거합니다.
    # [2차 업무 설명]: 이름표가 빈칸이거나 스페이스바만 쳐져 있지 않은지 확인하고 앞뒤 공백을 다듬는 일입니다.
    def __post_init__(self) -> None:
        # [1차 설명]: 카테고리 이름이 비어있거나 스페이스 공백만 있는지 검사합니다.
        # [2차 업무 설명]: 아무 이름도 없는 투명 이름표는 분류로 쓸 수 없으므로 거절합니다.
        if not self.name or not self.name.strip():
            # [1차 설명]: 이름이 공백일 수 없다는 에러를 발생시킵니다.
            # [2차 업무 설명]: 이름을 똑바로 적으라고 거절 안내를 던집니다.
            raise ValueError("카테고리 이름은 공백일 수 없습니다.")
        # [1차 설명]: 이름 앞뒤의 불필요한 공백 빈칸을 제거합니다.
        # [2차 업무 설명]: " 식비 " 처럼 실수로 넣은 빈칸을 다듬어 깨끗한 "식비"로 만듭니다.
        self.name = self.name.strip()

    # [1차 설명]: 카테고리 이름을 딕셔너리로 바꿉니다.
    # [2차 업무 설명]: 장부 파일에 적기 위해 이름표를 포장하는 일입니다.
    def to_dict(self) -> dict[str, str]:
        # [1차 설명]: 카테고리 이름을 담은 딕셔너리를 반환합니다.
        # [2차 업무 설명]: {"name": "식비"} 형태로 포장합니다.
        return {"name": self.name}

    # [1차 설명]: 딕셔너리에서 카테고리 객체를 복원합니다.
    # [2차 업무 설명]: 파일에 적힌 이름으로 새 카테고리 이름표를 꺼내는 일입니다.
    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "Category":
        # [1차 설명]: name 글자를 꺼내어 새 Category 객체로 만들어 반환합니다.
        # [2차 업무 설명]: 파일에서 읽은 글자로 공식 카테고리 명찰을 만듭니다.
        return cls(name=str(data["name"]))